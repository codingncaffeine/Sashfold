#!/usr/bin/env python3
# Writes src/text/VowelConstraintsData.h: the character sequences the
# OpenType script development specifications prohibit (an independent
# vowel followed by a dependent vowel that together look like another
# independent vowel, and a few more), from the specifications' data file
# IndicShapingInvalidCluster.txt (tools/ucd-fetch.sh puts it in ucd/p17).
# The shapers draw a dotted circle into such a sequence, before its last
# character.
#   tools/gen-vowel-constraints.py ucd/p17/IndicShapingInvalidCluster.txt > src/text/VowelConstraintsData.h
import sys

sequences = []
for line in open(sys.argv[1], encoding='utf-8'):
    data = line.split('#', 1)[0].split(';', 1)[0].strip()
    if not data:
        continue
    codes = [int(x, 16) for x in data.split()]
    if not 2 <= len(codes) <= 3:
        sys.exit(f'unexpected sequence length: {line.strip()}')
    sequences.append(codes + [0] * (3 - len(codes)))
sequences = sorted(set(tuple(s) for s in sequences))

print('#pragma once')
print()
print('// Generated by tools/gen-vowel-constraints.py from IndicShapingInvalidCluster.txt')
print('// (the prohibited sequences of the OpenType script development specifications).')
print('// Do not edit.')
print()
print('#include <array>')
print()
print('namespace sashfold::text::shaping::vowel_constraints {')
print()
print('// Each sequence, 0 past its end, sorted.')
print(f'inline constexpr std::array<std::array<char32_t, 3>, {len(sequences)}> sequences {{ {{')
for s in sequences:
    print('    { ' + ', '.join(f'0x{c:04X}' for c in s) + ' },')
print('} };')
print()
print('}')
