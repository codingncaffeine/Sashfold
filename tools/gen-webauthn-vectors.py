#!/usr/bin/env python3
# Writes tests/WebAuthnVectors.h: the hex literals of the W3C Web
# Authentication Level 3 Recommendation's section 16 "Test Vectors"
# (https://www.w3.org/TR/webauthn-3/), the registration and authentication
# ceremonies the security-key tests read and verify. Only the values are
# taken, each under its section number; nothing is computed here.
#
#   tools/gen-webauthn-vectors.py <saved webauthn-3 HTML> [out.h]
import html, re, sys

source = open(sys.argv[1], encoding='utf-8').read()
out_path = sys.argv[2] if len(sys.argv) > 2 else 'tests/WebAuthnVectors.h'

source = re.sub(r'<script.*?</script>', '', source, flags=re.S)
source = re.sub(r'<style.*?</style>', '', source, flags=re.S)
text = html.unescape(re.sub(r'<[^>]+>', '', source)).splitlines()

start = next(i for i, line in enumerate(text) if line.strip() == '16. Test Vectors')
sections = {}
current = None
part = 'top'
for line in text[start:]:
    heading = re.match(r'\s+(16\.\d+(?:\.\d+)*)\. (.*)', line)
    if heading:
        current = heading.group(1)
        sections[current] = {'title': heading.group(2).strip(), 'top': {}, 'Registration': {}, 'Authentication': {}}
        part = 'top'
        continue
    if current is None:
        continue
    stripped = line.strip()
    if stripped in ('Registration:', 'Authentication:'):
        part = stripped[:-1]
        continue
    value = re.match(r"([a-zA-Z_0-9]+) = (?:[^h]*?)h'([0-9a-f]+)'", stripped)
    if value:
        sections[current][part][value.group(1)] = value.group(2)

wanted = ['16.2', '16.3', '16.7', '16.8', '16.9', '16.10', '16.11', '16.16']
fields = [('Registration', 'credential_private_key'), ('Registration', 'private_key'), ('Registration', 'private_key_p'),
          ('Registration', 'private_key_q'), ('Registration', 'aaguid'), ('Registration', 'credential_id'),
          ('Registration', 'attestation_private_key'), ('Registration', 'clientDataJSON'), ('Registration', 'attestationObject'),
          ('Authentication', 'authenticatorData'), ('Authentication', 'clientDataJSON'), ('Authentication', 'signature')]

out = ['// Generated by tools/gen-webauthn-vectors.py from the W3C Web Authentication',
       '// Level 3 Recommendation, section 16 "Test Vectors"; the section numbers are',
       "// the specification's. Do not edit by hand.",
       '#pragma once', '', 'struct WebAuthnVector {', '    char const* section;', '    char const* title;']
for part, field in fields:
    out.append('    char const* %s%s;' % ('reg_' if part == 'Registration' else 'auth_', field))
out += ['};', '', '// §16.1', 'inline char const* const attestation_ca_cert = "%s";' % sections['16.1']['top']['attestation_ca_cert'], '',
        'inline WebAuthnVector const webauthn_vectors[] = {']
for number in wanted:
    section = sections[number]
    out.append('    { "%s", "%s",' % (number, section['title'].replace('"', '\\"')))
    for part, field in fields:
        out.append('        "%s",' % section[part].get(field, ''))
    out.append('    },')
out.append('};')
open(out_path, 'w').write('\n'.join(out) + '\n')
