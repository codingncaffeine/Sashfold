#!/usr/bin/env python3
# Writes src/media/SbrData.cpp: the tables of ISO/IEC 14496-3 §4.6.18 an
# SBR decoder reads — the ten Huffman codebooks of the envelope and noise
# floor deltas (Tables 4.A.83 to 4.A.92) as canonical codewords, the
# start frequency tables (Table 4.A.78), the QMF bank's prototype filter
# (Table 4.A.87), the noise generator's random phases (Table 4.A.86), the
# limiter's gains and bands per octave and the smoothing filter, and the
# six codebooks of parametric stereo's parameter deltas (§8.6.4: the
# IID at either quantization and the ICC, each by time and by
# frequency) — taken
# from the freely published reference decoder of 3GPP TS 26.410 (its
# sbr_rom.c), where the codebooks stand as binary trees with negative
# leaves and the prototype as 325 polyphase coefficients: the trees are
# walked here and the codewords written out canonical, the prototype
# unfolded to its 640 coefficients by the symmetry it has (checked below
# by the filter bank's perfect reconstruction in test_aac), so the data is
# the standard's and the form is ours. Each codebook's Kraft sum is checked.
#
#   tools/gen-sbr-tables.py <path to sbr_rom.c> [out.cpp]
import re, sys
from fractions import Fraction

rom = open(sys.argv[1], encoding='latin-1').read()
out_path = sys.argv[2] if len(sys.argv) > 2 else 'src/media/SbrData.cpp'


def floats(name):
    m = re.search(r'%s\s*\[[^=]*=\s*\{(.*?)\n\};' % re.escape(name), rom, re.S)
    body = re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S)
    return [float(x) for x in re.findall(r'[-+]?\d+\.\d+(?:e[-+]?\d+)?', body)]


def ints(name):
    m = re.search(r'%s\s*\[[^=]*=\s*\{([^}]*)\}' % re.escape(name), rom)
    return [int(x) for x in re.findall(r'-?\d+', m.group(1))]


def tree(name):
    m = re.search(r'%s\s*\[\d+\]\[2\]\s*=\s*\{(.*?)\n\};' % re.escape(name), rom, re.S)
    rows = re.findall(r'\{\s*(-?\d+)\s*,\s*(-?\d+)\s*\}', m.group(1))
    return [[int(a), int(b)] for a, b in rows]


# A node holds two entries, one per bit; an entry below zero is a leaf
# whose decoded delta is the entry plus 64 (a leaf of -64 is a delta of
# zero, -65 of minus one, -63 of plus one), one at or above zero the next node.
lav_of_current = 0


def codewords(nodes):
    found = []
    def walk(node, code, length):
        for bit in range(2):
            entry = nodes[node][bit]
            c = (code << 1) | bit
            if entry < 0:
                found.append((c, length + 1, entry + 64))
            else:
                walk(entry, c, length + 1)
    walk(0, 0, 0)
    kraft = sum(Fraction(1, 2 ** length) for _, length, _ in found)
    assert kraft == 1, (kraft, len(found))
    deltas = sorted(d for _, _, d in found)
    assert deltas == list(range(-lav_of_current, lav_of_current + 1)), (deltas[0], deltas[-1], len(deltas))
    found.sort(key=lambda e: (e[1], e[0]))
    return found


# (name, lav): the largest absolute value the book codes; index - lav is the delta.
BOOKS = [
    ('sbr_huffBook_EnvLevel10T', 60), ('sbr_huffBook_EnvLevel10F', 60),
    ('sbr_huffBook_EnvBalance10T', 24), ('sbr_huffBook_EnvBalance10F', 24),
    ('sbr_huffBook_EnvLevel11T', 31), ('sbr_huffBook_EnvLevel11F', 31),
    ('sbr_huffBook_EnvBalance11T', 12), ('sbr_huffBook_EnvBalance11F', 12),
    ('sbr_huffBook_NoiseLevel11T', 31), ('sbr_huffBook_NoiseBalance11T', 12),
]

# Parametric stereo's books, in the order ps_books holds them.
PS_BOOKS = [
    ('aBookPsIidTimeDecode', 14), ('aBookPsIidFreqDecode', 14),
    ('aBookPsIidFineTimeDecode', 30), ('aBookPsIidFineFreqDecode', 30),
    ('aBookPsIccTimeDecode', 7), ('aBookPsIccFreqDecode', 7),
]


def short_name(name):
    return name.replace('sbr_huffBook_', '').replace('aBook', '').replace('Decode', '')

out = []
out.append('// Generated by tools/gen-sbr-tables.py from the tables of ISO/IEC 14496-3')
out.append('// §4.6.18 as 3GPP TS 26.410\'s reference decoder publishes them; do not edit.')
out.append('')
out.append('#include "media/SbrData.h"')
out.append('')
out.append('namespace sashfold::media::sbr_data {')
out.append('')
out.append('namespace {')
out.append('')
for name, lav in BOOKS + PS_BOOKS:
    lav_of_current = lav
    entries = codewords(tree(name))
    short = short_name(name)
    out.append('HuffmanEntry const k_%s[%d] = {' % (short, len(entries)))
    line = '   '
    for code, length, delta in entries:
        piece = ' { %d, %d, 0x%X },' % (delta, length, code)
        if len(line) + len(piece) > 118:
            out.append(line)
            line = '   '
        line += piece
    out.append(line)
    out.append('};')
    out.append('')

def lit(v, digits):
    text = ('%%.%dg' % digits) % v
    return text + ('f' if '.' in text or 'e' in text else '.0f')


# The QMF prototype: 325 values stored five to a row for 65 rows, as the
# reference's polyphase filter walks them — row m (0 to 63) column i
# holding p[1 + m + 128 i], the 65th row the four at the multiples of 128
# (see below); the other half by the filter's symmetry, p[n] = p[640 - n],
# and p[0] = 0.
stored = floats('sbr_qmf_64_640')
assert len(stored) == 325, len(stored)
p = [None] * 640
p[0] = 0.0
for m in range(64):
    for i in range(5):
        p[1 + m + 128 * i] = stored[m * 5 + i]
# The 65th row is {-p[128], -p[256], -p[384], -p[512], p[640] = 0}: the
# four coefficients at the multiples of 128, negated for the reference's
# reversed walk. They are the four the symmetry below does not give: the
# standard's window is symmetric about 320 everywhere but there, where
# p[256] = -p[384] and p[128] = -p[512].
assert abs(stored[320] + stored[323]) < 1e-9 and abs(stored[321] + stored[322]) < 1e-9 and abs(stored[324]) < 1e-9
for i in range(4):
    p[128 * (i + 1)] = -stored[320 + i]
for n in range(640):
    if p[n] is None:
        p[n] = p[640 - n]
assert all(v is not None for v in p)
# Known anchors of Table 4.A.87.
assert abs(p[1] - -0.00055252865047) < 1e-12 and abs(p[2] - -0.00056176925738) < 1e-12
assert abs(p[639] - p[1]) < 1e-12

start = {rate: ints('sbr_start_freq_%d' % rate) for rate in (16, 22, 24, 32, 44, 48)}
phases = floats('sbr_randomPhase')
assert len(phases) == 1024, len(phases)
lim_gains = floats('sbr_limGains')
lim_bands = floats('sbr_limiterBandsPerOctave')
smooth = floats('sbr_smoothFilter')
assert len(lim_gains) == 4 and len(lim_bands) == 4 and len(smooth) == 4

out.append('} // namespace')
out.append('')
out.append('HuffmanBook const books[%d] = {' % len(BOOKS))
for name, lav in BOOKS:
    short = short_name(name)
    lav_of_current = lav
    out.append('    { %d, k_%s, %d },' % (lav, short, len(codewords(tree(name)))))
out.append('};')
out.append('')
out.append('HuffmanBook const ps_books[%d] = {' % len(PS_BOOKS))
for name, lav in PS_BOOKS:
    short = short_name(name)
    lav_of_current = lav
    out.append('    { %d, k_%s, %d },' % (lav, short, len(codewords(tree(name)))))
out.append('};')
out.append('')
for rate in (16, 22, 24, 32, 44, 48):
    out.append('std::uint8_t const start_freq_%d[16] = { %s };' % (rate, ', '.join(str(v) for v in start[rate])))
out.append('')
out.append('float const qmf_prototype[640] = {')
for i in range(0, 640, 5):
    out.append('    ' + ', '.join(lit(v, 16) for v in p[i:i + 5]) + ',')
out.append('};')
out.append('')
out.append('float const random_phase[512][2] = {')
for i in range(0, 1024, 8):
    out.append('    ' + ', '.join('{ %s, %s }' % (lit(phases[j], 14), lit(phases[j + 1], 14)) for j in range(i, i + 8, 2)) + ',')
out.append('};')
out.append('')
def lit(v, digits):
    text = ('%%.%dg' % digits) % v
    return text + ('f' if '.' in text or 'e' in text else '.0f')


out.append('float const limiter_gains[4] = { %s };' % ', '.join(lit(v, 10) for v in lim_gains))
out.append('float const limiter_bands_per_octave[4] = { %s };' % ', '.join(lit(v, 10) for v in lim_bands))
out.append('float const smooth_filter[4] = { %s };' % ', '.join(lit(v, 14) for v in smooth))
out.append('')
out.append('}')
out.append('')
open(out_path, 'w').write('\n'.join(out))
print('wrote', out_path)
