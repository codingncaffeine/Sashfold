#!/usr/bin/env python3
# Writes src/js/TimeZoneData.cpp: the IANA time zone database carried in the
# engine, as browsers carry it (in their ICU data), so a time zone means the
# same on every machine — Windows has no zoneinfo at all, and distributions
# leave names out (Debian and Ubuntu put the old ones in tzdata-legacy).
# Every Zone of tzdata.zi as its compiled TZif file, and every Link, from a
# system zoneinfo of the version wanted.
#   tools/gen-tz-data.py [/usr/share/zoneinfo] > src/js/TimeZoneData.cpp
import os, sys

root = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/zoneinfo'
version = 'unknown'
zones, links = [], []
with open(os.path.join(root, 'tzdata.zi'), encoding='utf-8') as zi:
    for line in zi:
        if line.startswith('# version '):
            version = line.split()[2]
        elif line.startswith('Z '):
            name = line.split()[1]
            if name != 'Factory':
                zones.append(name)
        elif line.startswith('L '):
            _, target, alias = line.split()[:3]
            links.append((alias, target))
zones.sort()
links.sort()

blob = bytearray()
entries = []
for name in zones:
    data = open(os.path.join(root, name), 'rb').read()
    assert data[:4] == b'TZif', name
    entries.append((name, len(blob), len(data)))
    blob += data

out = sys.stdout
out.write('// Generated by tools/gen-tz-data.py from the IANA time zone database,\n')
out.write('// version %s: %d zones (%d bytes of TZif) and %d links. Do not edit.\n\n' % (version, len(zones), len(blob), len(links)))
out.write('#include "js/TimeZone.h"\n\nnamespace sashfold::js {\n\nnamespace {\n\n')
out.write('constexpr unsigned char bytes[] = {')
for i, b in enumerate(blob):
    out.write(('\n    ' if i % 24 == 0 else ' ') + '%d,' % b)
out.write('\n};\n\n')
out.write('constexpr EmbeddedZone zones[] = {\n')
for name, offset, size in entries:
    out.write('    { "%s", %d, %d },\n' % (name, offset, size))
out.write('};\n\n')
out.write('constexpr TimeZoneLink links[] = {\n')
for alias, target in links:
    out.write('    { "%s", "%s" },\n' % (alias, target))
out.write('};\n\n} // namespace\n\n')
out.write('char const* time_zone_database_version()\n{\n    return "%s";\n}\n\n' % version)
out.write('std::span<EmbeddedZone const> embedded_zones()\n{\n    return zones;\n}\n\n')
out.write('std::span<unsigned char const> embedded_zone_bytes()\n{\n    return bytes;\n}\n\n')
out.write('std::span<TimeZoneLink const> time_zone_links()\n{\n    return links;\n}\n\n}\n')
