#!/usr/bin/env python3
# Writes src/js/TimeZoneLinks.cpp: the IANA time zone database's links (an
# old or alternative name and the zone it names: Asia/Calcutta is
# Asia/Kolkata), read from the database's tzdata.zi ("L target alias"
# lines). Browsers carry these in their own data; a system's zoneinfo
# may leave the old names out (Debian and Ubuntu moved them to
# tzdata-legacy), and ECMA-402 still accepts every one.
#   tools/gen-tz-links.py [/usr/share/zoneinfo/tzdata.zi] > src/js/TimeZoneLinks.cpp
import sys

path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo/tzdata.zi"
version = "unknown"
links = []
with open(path, encoding="utf-8") as zi:
    for line in zi:
        if line.startswith("# version "):
            version = line.split()[2]
        elif line.startswith("L "):
            _, target, alias = line.split()[:3]
            links.append((alias, target))
links.sort()

out = sys.stdout
out.write("// Generated by tools/gen-tz-links.py from the IANA time zone database,\n")
out.write("// version %s: %d links, alias then target. Do not edit.\n\n" % (version, len(links)))
out.write('#include "js/TimeZone.h"\n\n')
out.write("namespace sashfold::js {\n\n")
out.write("namespace {\n\n")
out.write("constexpr TimeZoneLink links[] = {\n")
for alias, target in links:
    out.write('    { "%s", "%s" },\n' % (alias, target))
out.write("};\n\n")
out.write("} // namespace\n\n")
out.write("std::span<TimeZoneLink const> time_zone_links()\n{\n    return links;\n}\n\n")
out.write("} // namespace sashfold::js\n")
