#!/usr/bin/env python3
# Writes src/pdf/ArabicFormsData.h: for each Arabic letter that has
# presentation forms (the Arabic Presentation Forms-A and -B blocks), its
# isolated, final, initial and medial form, and the lam-alef ligatures,
# all read from the <isolated>, <final>, <initial> and <medial>
# compatibility decompositions of UnicodeData.txt; and the code points in
# the Arabic blocks whose general category is Mn or Me, which joining
# skips over (joining type T, Unicode §9.2 "Arabic Cursive Joining").
# A letter with an initial or medial form joins on both sides (type D),
# one with only isolated and final forms on its right (type R).
#   tools/gen-arabic-forms.py ucd/UnicodeData.txt > src/pdf/ArabicFormsData.h
import sys

forms = {}  # base -> {tag: form}
lam_alef = {}  # alef -> {tag: form}
marks = []
for line in open(sys.argv[1], encoding='utf-8'):
    fields = line.rstrip('\n').split(';')
    code = int(fields[0], 16)
    category = fields[2]
    decomposition = fields[5]
    if 0x0600 <= code <= 0x08FF and category in ('Mn', 'Me'):
        marks.append(code)
    if not (0xFB50 <= code <= 0xFDFF or 0xFE70 <= code <= 0xFEFF):
        continue
    if not decomposition.startswith('<'):
        continue
    tag, _, rest = decomposition.partition(' ')
    tag = tag.strip('<>')
    if tag not in ('isolated', 'final', 'initial', 'medial'):
        continue
    parts = [int(p, 16) for p in rest.split()]
    if len(parts) == 1:
        forms.setdefault(parts[0], {}).setdefault(tag, code)
    elif len(parts) == 2 and parts[0] == 0x0644 and parts[1] in (0x0622, 0x0623, 0x0625, 0x0627):
        lam_alef.setdefault(parts[1], {}).setdefault(tag, code)

ranges = []
for code in sorted(marks):
    if ranges and ranges[-1][1] + 1 == code:
        ranges[-1][1] = code
    else:
        ranges.append([code, code])

print('// The Arabic presentation forms by letter, the lam-alef ligatures, and')
print('// the marks joining skips over, from UnicodeData.txt.')
print('// Generated by tools/gen-arabic-forms.py; do not edit by hand.')
print('#pragma once')
print()
print('namespace sashfold::pdf {')
print()
print('struct ArabicLetterForms {')
print('    char32_t letter;')
print('    char32_t isolated, final, initial, medial; // 0: none')
print('};')
print()
print('inline constexpr ArabicLetterForms arabic_letter_forms[] = {')
for base in sorted(forms):
    f = forms[base]
    print('    { 0x%04X, 0x%04X, 0x%04X, 0x%04X, 0x%04X },' % (
        base, f.get('isolated', 0), f.get('final', 0), f.get('initial', 0), f.get('medial', 0)))
print('};')
print()
print('// Lam followed by an alef: one ligature, isolated or final.')
print('struct ArabicLamAlef {')
print('    char32_t alef;')
print('    char32_t isolated, final;')
print('};')
print()
print('inline constexpr ArabicLamAlef arabic_lam_alef[] = {')
for alef in sorted(lam_alef):
    f = lam_alef[alef]
    print('    { 0x%04X, 0x%04X, 0x%04X },' % (alef, f.get('isolated', 0), f.get('final', 0)))
print('};')
print()
print('struct ArabicMarkRange {')
print('    char32_t first, last;')
print('};')
print()
print('inline constexpr ArabicMarkRange arabic_transparent[] = {')
for first, last in ranges:
    print('    { 0x%04X, 0x%04X },' % (first, last))
print('};')
print()
print('}')
