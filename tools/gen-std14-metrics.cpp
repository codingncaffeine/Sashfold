// Writes src/pdf/Std14Metrics.cpp: the advance widths of PDF's standard 14
// fonts, which a reader must know without the fonts (ISO 32000-2 §9.6.2.2),
// so a page that names Helvetica without /Widths lays its text out the
// same with or without a font on the machine. Measured from the URW base 35
// fonts (metric-compatible with the 14, and what the substitutes are) with
// the engine's own font reader: the twelve text fonts by glyph name (every
// name of the standard, WinAnsi and MacRoman encodings), Symbol and
// ZapfDingbats by code, as their fonts' cmaps key them.
//   gen_std14_metrics <folder of URW .otf files> > src/pdf/Std14Metrics.cpp

#include "pdf/Encoding.h"
#include "text/TrueType.h"

#include <algorithm>
#include <cmath>
#include <cstdio>
#include <fstream>
#include <iterator>
#include <optional>
#include <set>
#include <string>
#include <vector>

using namespace sashfold;

namespace {

std::optional<text::TrueTypeFont> open(std::string const& path)
{
    std::ifstream file(path, std::ios::binary);
    std::vector<std::uint8_t> bytes((std::istreambuf_iterator<char>(file)), std::istreambuf_iterator<char>());
    if (bytes.empty())
        return std::nullopt;
    return text::TrueTypeFont::parse(std::move(bytes));
}

int per_thousand(text::TrueTypeFont const& font, std::uint16_t glyph)
{
    return static_cast<int>(std::lround(font.advance_width(glyph) * 1000.0 / font.units_per_em()));
}

} // namespace

int main(int argc, char** argv)
{
    if (argc != 2) {
        std::fprintf(stderr, "usage: gen_std14_metrics <folder of URW .otf files>\n");
        return 2;
    }
    std::string const folder = argv[1];
    struct Face {
        char const* name; // the standard name
        char const* file;
    };
    Face const text_faces[] = {
        { "Helvetica", "NimbusSans-Regular.otf" }, { "Helvetica-Bold", "NimbusSans-Bold.otf" },
        { "Helvetica-Oblique", "NimbusSans-Italic.otf" }, { "Helvetica-BoldOblique", "NimbusSans-BoldItalic.otf" },
        { "Times-Roman", "NimbusRoman-Regular.otf" }, { "Times-Bold", "NimbusRoman-Bold.otf" },
        { "Times-Italic", "NimbusRoman-Italic.otf" }, { "Times-BoldItalic", "NimbusRoman-BoldItalic.otf" },
        { "Courier", "NimbusMonoPS-Regular.otf" }, { "Courier-Bold", "NimbusMonoPS-Bold.otf" },
        { "Courier-Oblique", "NimbusMonoPS-Italic.otf" }, { "Courier-BoldOblique", "NimbusMonoPS-BoldItalic.otf" },
    };
    Face const symbol_faces[] = { { "Symbol", "StandardSymbolsPS.otf" }, { "ZapfDingbats", "D050000L.otf" } };

    // The names the encodings use.
    std::set<std::string> names;
    for (pdf::BaseEncoding encoding : { pdf::BaseEncoding::Standard, pdf::BaseEncoding::WinAnsi, pdf::BaseEncoding::MacRoman }) {
        for (char const* name : pdf::base_encoding(encoding)) {
            if (name && *name)
                names.insert(name);
        }
    }

    std::printf("// Generated by tools/gen-std14-metrics.cpp from the URW base 35 fonts (metric-compatible\n");
    std::printf("// with the standard 14). Do not edit.\n\n#include \"pdf/Std14Metrics.h\"\n\n");
    std::printf("namespace sashfold::pdf {\n\nnamespace {\n\n");
    int index = 0;
    for (Face const& face : text_faces) {
        std::optional<text::TrueTypeFont> font = open(folder + "/" + face.file);
        if (!font) {
            std::fprintf(stderr, "cannot read %s\n", face.file);
            return 1;
        }
        std::printf("constexpr NamedWidth face%d[] = {\n", index++);
        for (std::string const& name : names) {
            std::u32string const text = pdf::glyph_name_unicode(name);
            if (text.size() != 1)
                continue;
            std::uint16_t const glyph = font->glyph_index(text[0]);
            if (glyph == 0)
                continue;
            std::printf("    { \"%s\", %d },\n", name.c_str(), per_thousand(*font, glyph));
        }
        std::printf("};\n");
    }
    for (Face const& face : symbol_faces) {
        std::optional<text::TrueTypeFont> font = open(folder + "/" + face.file);
        if (!font) {
            std::fprintf(stderr, "cannot read %s\n", face.file);
            return 1;
        }
        // Their (3,1) cmap is keyed by the font's own codes.
        std::printf("constexpr short codes%d[256] = {", index++);
        for (int code = 0; code < 256; ++code) {
            std::optional<std::uint16_t> const glyph = font->subtable_glyph(3, 1, static_cast<char32_t>(code));
            int const width = glyph && *glyph ? per_thousand(*font, *glyph) : 0;
            std::printf("%s%d,", code % 16 ? " " : "\n    ", width);
        }
        std::printf("\n};\n");
    }
    std::printf("\n} // namespace\n\nstd::optional<Std14Widths> std14_widths(std::string_view name)\n{\n");
    index = 0;
    for (Face const& face : text_faces) {
        std::printf("    if (name == \"%s\")\n        return Std14Widths { face%d, nullptr };\n", face.name, index);
        ++index;
    }
    for (Face const& face : symbol_faces) {
        std::printf("    if (name == \"%s\")\n        return Std14Widths { {}, codes%d };\n", face.name, index);
        ++index;
    }
    std::printf("    return std::nullopt;\n}\n\n}\n");
    return 0;
}
