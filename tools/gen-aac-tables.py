#!/usr/bin/env python3
# Writes src/media/AacData.cpp: the tables of ISO/IEC 14496-3 an AAC
# decoder reads — the twelve Huffman codebooks (Tables 4.A.2 to 4.A.13,
# the spectrum's eleven and the scalefactors') as codeword, length and
# index, and the scalefactor band offsets of the long and short windows by
# sampling rate (Tables 4.129 to 4.142) — taken from the freely published
# reference decoder of 3GPP TS 26.410 (its aac_rom.c), where the codebooks
# stand as two-bits-at-a-time trees: the trees are walked here and the
# codewords written out canonical, so the data is the standard's and the
# form is ours. Each codebook's Kraft sum is checked to be exactly one.
#
#   tools/gen-aac-tables.py <path to aac_rom.c> [out.cpp]
import re, sys
from fractions import Fraction

rom = open(sys.argv[1], encoding='latin-1').read()
out_path = sys.argv[2] if len(sys.argv) > 2 else 'src/media/AacData.cpp'

def table(name):
    m = re.search(r'%s\[\]\s*=\s*\{([^}]*)\}' % re.escape(name), rom)
    return [int(x) for x in re.findall(r'-?\d+', m.group(1))]

def tree(name):
    m = re.search(r'%s\[\d+\]\[4\]\s*=\s*\{(.*?)\n\};' % re.escape(name), rom, re.S)
    rows = re.findall(r'\{\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*\}', m.group(1))
    return [[int(v, 16) for v in row] for row in rows]

# A tree node holds four entries, one per pair of bits read; an entry with
# bit 0 set is a leaf whose value is in bits 2 and up, and whose codeword
# is one bit shorter than the bits read when bit 1 is set (the second of
# the pair is not part of it, and two entries share the leaf).
def codewords(nodes):
    found = {}
    def walk(node, code, length):
        for two in range(4):
            entry = nodes[node][two]
            c = (code << 2) | two
            if entry & 1:
                value = entry >> 2
                if entry & 2:
                    cw, ln = c >> 1, length + 1
                else:
                    cw, ln = c, length + 2
                if value in found:
                    assert found[value] == (ln, cw), (value, found[value], (ln, cw))
                else:
                    found[value] = (ln, cw)
            else:
                walk(entry >> 2, c, length + 2)
    walk(0, 0, 0)
    kraft = sum(Fraction(1, 2 ** ln) for ln, _ in found.values())
    assert kraft == 1, kraft
    return [(index, ln, cw) for index, (ln, cw) in sorted(found.items())]

# Dimension, bits per value, offset (the unsigned books' values are
# unsigned; the signed ones' are value - offset), as Table 4.A.1 has them.
books = [
    ('HuffmanCodeBook_1', 4, 2, 1), ('HuffmanCodeBook_2', 4, 2, 1), ('HuffmanCodeBook_3', 4, 2, 0), ('HuffmanCodeBook_4', 4, 2, 0),
    ('HuffmanCodeBook_5', 2, 4, 4), ('HuffmanCodeBook_6', 2, 4, 4), ('HuffmanCodeBook_7', 2, 4, 0), ('HuffmanCodeBook_8', 2, 4, 0),
    ('HuffmanCodeBook_9', 2, 4, 0), ('HuffmanCodeBook_10', 2, 4, 0), ('HuffmanCodeBook_11', 2, 5, 0), ('HuffmanCodeBook_SCL', 1, 8, 60),
]
expected_sizes = [81, 81, 81, 81, 81, 81, 64, 64, 169, 169, 289, 121]

lines = []
lines.append('// Generated by tools/gen-aac-tables.py from 3GPP TS 26.410\'s reference')
lines.append('// decoder tables (the codebooks walked out of its trees and written')
lines.append('// canonical): ISO/IEC 14496-3 Tables 4.A.2 to 4.A.13 and 4.129 to 4.142.')
lines.append('// Do not edit by hand.')
lines.append('#include "media/AacData.h"')
lines.append('')
lines.append('namespace sashfold::media::aac_data {')
lines.append('')
for (name, dim, bits, offset), expected in zip(books, expected_sizes):
    entries = codewords(tree(name))
    assert len(entries) == expected, (name, len(entries))
    short = name.replace('HuffmanCodeBook_', 'book_').lower()
    lines.append('static constexpr HuffmanEntry %s_entries[%d] = {' % (short, len(entries)))
    row = []
    for index, ln, cw in entries:
        row.append('{ %d, %d, 0x%x }' % (index, ln, cw))
        if len(row) == 6:
            lines.append('    ' + ', '.join(row) + ',')
            row = []
    if row:
        lines.append('    ' + ', '.join(row) + ',')
    lines.append('};')
    lines.append('')
lines.append('HuffmanBook const books[12] = {')
for (name, dim, bits, offset), expected in zip(books, expected_sizes):
    short = name.replace('HuffmanCodeBook_', 'book_').lower()
    lines.append('    { %d, %d, %d, %s_entries, %d },' % (dim, bits, offset, short, expected))
lines.append('};')
lines.append('')

# The scalefactor bands by sampling rate, as the reference carries them
# (8 to 48 kHz; 64, 88.2 and 96 kHz are owed).
bands = [
    ('sfb_48_1024', 'sfb_48_128', [48000, 44100]), ('sfb_32_1024', 'sfb_48_128', [32000]), ('sfb_24_1024', 'sfb_24_128', [24000, 22050]),
    ('sfb_16_1024', 'sfb_16_128', [16000, 12000, 11025]), ('sfb_8_1024', 'sfb_8_128', [8000]),
]
emitted = set()
for long_name, short_name, rates in bands:
    for n in (long_name, short_name):
        if n in emitted:
            continue
        emitted.add(n)
        values = table(n)
        assert values[0] == 0 and values[-1] in (1024, 128)
        lines.append('static constexpr std::uint16_t %s[%d] = { %s };' % (n, len(values), ', '.join(str(v) for v in values)))
lines.append('')
# TNS's highest band by sampling rate (Table 4.139), long and short windows.
tns = re.search(r'tns_max_bands_tbl\[9\]\[2\]\s*=\s*\{(.*?)\};', rom, re.S).group(1)
tns_rows = [(int(a), int(b)) for a, b in re.findall(r'\{\s*(\d+)\s*,\s*(\d+)\s*\}', tns)]
tns_by_rate = dict(zip([48000, 44100, 32000, 24000, 22050, 16000, 12000, 11025, 8000], tns_rows))
lines.append('BandTable const band_tables[] = {')
for long_name, short_name, rates in bands:
    for rate in rates:
        lines.append('    { %d, %s, %d, %s, %d, %d, %d },' % (rate, long_name, len(table(long_name)) - 1, short_name, len(table(short_name)) - 1,
            tns_by_rate[rate][0], tns_by_rate[rate][1]))
lines.append('};')
lines.append('std::size_t const band_table_count = %d;' % sum(len(r) for _, _, r in bands))
lines.append('')
lines.append('}')
lines.append('')
open(out_path, 'w').write('\n'.join(lines))
print('wrote', out_path, 'with', len(books), 'codebooks')
