bool looks_like_webp(std::vector<std::uint8_t> const& bytes)
{
    return bytes.size() >= 12 && std::memcmp(bytes.data(), "RIFF", 4) == 0 && std::memcmp(bytes.data() + 8, "WEBP", 4) == 0;
}

std::optional<Bitmap> decode_webp(std::vector<std::uint8_t> const& bytes, std::size_t max_pixels)
{
    if (!looks_like_webp(bytes))
        return std::nullopt;
    std::size_t const riff_size = std::min<std::size_t>(le32(bytes.data() + 4), bytes.size() - 8);
    if (riff_size < 4)
        return std::nullopt;
    std::vector<Chunk> const chunks = chunks_of(bytes.data() + 12, riff_size - 4);
    if (chunks.empty())
        return std::nullopt;
    if (chunks.front().fourcc != fourcc("VP8X"))
        return decode_frame(chunks, max_pixels);
    // The extended format: a canvas, and either one picture or an animation,
    // which shows its first frame where it stands on the canvas.
    Chunk const& header = chunks.front();
    if (header.size < 10)
        return std::nullopt;
    int const canvas_width = static_cast<int>(le24(header.data + 4)) + 1;
    int const canvas_height = static_cast<int>(le24(header.data + 7)) + 1;
    if (static_cast<std::size_t>(canvas_width) * static_cast<std::size_t>(canvas_height) > max_pixels)
        return std::nullopt;
    for (Chunk const& chunk : chunks) {
        if (chunk.fourcc != fourcc("ANMF"))
            continue;
        if (chunk.size < 16)
            return std::nullopt;
        int const fx = static_cast<int>(le24(chunk.data)) * 2;
        int const fy = static_cast<int>(le24(chunk.data + 3)) * 2;
        std::optional<Bitmap> frame = decode_frame(chunks_of(chunk.data + 16, chunk.size - 16), max_pixels);
        if (!frame)
            return std::nullopt;
        std::vector<std::uint8_t> canvas(static_cast<std::size_t>(canvas_width) * static_cast<std::size_t>(canvas_height) * 4, 0);
        for (int y = 0; y < frame->height() && fy + y < canvas_height; ++y) {
            for (int x = 0; x < frame->width() && fx + x < canvas_width; ++x) {
                std::size_t const from = (static_cast<std::size_t>(y) * static_cast<std::size_t>(frame->width()) + static_cast<std::size_t>(x)) * 4;
                std::size_t const to = (static_cast<std::size_t>(fy + y) * static_cast<std::size_t>(canvas_width) + static_cast<std::size_t>(fx + x)) * 4;
                std::memcpy(canvas.data() + to, frame->pixels().data() + from, 4);
            }
        }
        return Bitmap(canvas_width, canvas_height, std::move(canvas));
    }
    std::vector<Chunk> rest(chunks.begin() + 1, chunks.end());
    return decode_frame(rest, max_pixels);
}

