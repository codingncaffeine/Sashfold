// The boolean entropy decoder (RFC 6386 §7.3), a byte at a time. Past the
// end of its data it reads zeros; the caller checks `overrun` afterwards.
class BoolDecoder {
public:
    BoolDecoder() = default;
    BoolDecoder(std::uint8_t const* data, std::size_t size)
        : m_data(data)
        , m_end(data + size)
    {
        m_value = (next_byte() << 8) | next_byte();
    }

    int read(int probability)
    {
        unsigned const split = 1 + (((m_range - 1) * static_cast<unsigned>(probability)) >> 8);
        unsigned const big_split = split << 8;
        int bit;
        if (m_value >= big_split) {
            bit = 1;
            m_range -= split;
            m_value -= big_split;
        } else {
            bit = 0;
            m_range = split;
        }
        while (m_range < 128) {
            m_value <<= 1;
            m_range <<= 1;
            if (++m_bit_count == 8) {
                m_bit_count = 0;
                m_value |= next_byte();
            }
        }
        return bit;
    }
    int literal(int bits)
    {
        int value = 0;
        while (bits-- > 0)
            value = (value << 1) | read(128);
        return value;
    }
    int signed_literal(int bits)
    {
        int const value = literal(bits);
        return read(128) ? -value : value;
    }
    // A flag, then the value it guards: 0 when the flag is clear.
    int optional_signed(int bits) { return read(128) ? signed_literal(bits) : 0; }
    int tree(std::int8_t const* tree, std::uint8_t const* probabilities)
    {
        int i = 0;
        while ((i = tree[i + read(probabilities[i >> 1])]) > 0) {
        }
        return -i;
    }
    // More than a couple of bytes read past the end: the stream is cut.
    bool overrun() const { return m_past_end > 2; }

private:
    unsigned next_byte()
    {
        if (m_data < m_end)
            return *m_data++;
        ++m_past_end;
        return 0;
    }

    std::uint8_t const* m_data = nullptr;
    std::uint8_t const* m_end = nullptr;
    unsigned m_value = 0;
    unsigned m_range = 255;
    int m_bit_count = 0;
    int m_past_end = 0;
};

