int large_value(BoolDecoder& d, std::uint8_t const* p)
{
    if (!d.read(p[3])) {
        if (!d.read(p[4]))
            return 2;
        return 3 + d.read(p[5]);
    }
    if (!d.read(p[6])) {
        if (!d.read(p[7]))
            return 5 + d.read(159);
        int v = 7 + 2 * d.read(165);
        return v + d.read(145);
    }
    static constexpr std::uint8_t cat3[] = { 173, 148, 140, 0 };
    static constexpr std::uint8_t cat4[] = { 176, 155, 140, 135, 0 };
    static constexpr std::uint8_t cat5[] = { 180, 157, 141, 134, 130, 0 };
    static constexpr std::uint8_t cat6[] = { 254, 254, 243, 230, 196, 177, 153, 140, 133, 130, 129, 0 };
    static constexpr std::uint8_t const* cats[] = { cat3, cat4, cat5, cat6 };
    int const bit1 = d.read(p[8]);
    int const bit0 = d.read(p[9 + bit1]);
    int const cat = 2 * bit1 + bit0;
    int v = 0;
    for (std::uint8_t const* t = cats[cat]; *t; ++t)
        v += v + d.read(*t);
    return v + 3 + (8 << cat);
}

// One block's tokens (RFC 6386 §13): dequantized into `out` in raster
// order; returns the position after the last non-zero coefficient — `first`
// when there is none.
int read_coefficients(BoolDecoder& d, std::uint8_t const (*bands)[3][11], int context, int first, int dc_q, int ac_q,
    std::int16_t* out)
{
    std::uint8_t const* p = bands[kBands[first]][context];
    int n = first;
    while (n < 16) {
        if (!d.read(p[0]))
            return n; // the end of the block
        while (!d.read(p[1])) { // a zero
            if (++n == 16)
                return 16;
            p = bands[kBands[n]][0];
        }
        int value;
        int next_context;
        if (!d.read(p[2])) {
            value = 1;
            next_context = 1;
        } else {
            value = large_value(d, p);
            next_context = 2;
        }
        if (d.read(128))
            value = -value;
        out[kZigzag[n]] = static_cast<std::int16_t>(value * (n > 0 ? ac_q : dc_q));
        if (++n < 16)
            p = bands[kBands[n]][next_context];
    }
    return 16;
}

// The inverse Walsh-Hadamard transform of the second-order block: the DC of
// each of the 16 luma blocks (RFC 6386 §14.3).
void inverse_wht(std::int16_t const* in, std::int16_t* blocks)
{
    int tmp[16];
    for (int i = 0; i < 4; ++i) {
        int const a0 = in[0 + i] + in[12 + i];
        int const a1 = in[4 + i] + in[8 + i];
        int const a2 = in[4 + i] - in[8 + i];
        int const a3 = in[0 + i] - in[12 + i];
        tmp[0 + i] = a0 + a1;
        tmp[8 + i] = a0 - a1;
        tmp[4 + i] = a3 + a2;
        tmp[12 + i] = a3 - a2;
    }
    for (int i = 0; i < 4; ++i) {
        int const dc = tmp[0 + i * 4] + 3;
        int const a0 = dc + tmp[3 + i * 4];
        int const a1 = tmp[1 + i * 4] + tmp[2 + i * 4];
        int const a2 = tmp[1 + i * 4] - tmp[2 + i * 4];
        int const a3 = dc - tmp[3 + i * 4];
        blocks[(i * 4 + 0) * 16] = static_cast<std::int16_t>((a0 + a1) >> 3);
        blocks[(i * 4 + 1) * 16] = static_cast<std::int16_t>((a3 + a2) >> 3);
        blocks[(i * 4 + 2) * 16] = static_cast<std::int16_t>((a0 - a1) >> 3);
        blocks[(i * 4 + 3) * 16] = static_cast<std::int16_t>((a3 - a2) >> 3);
    }
}

// The inverse DCT of one block, added to the prediction under it (RFC 6386
// §14.4): columns first, then rows, rounded at the end.
void add_inverse_dct(std::int16_t const* in, std::uint8_t* dst, int stride)
{
    auto const mul1 = [](int a) { return ((a * 20091) >> 16) + a; };
    auto const mul2 = [](int a) { return (a * 35468) >> 16; };
    int c[16];
    for (int i = 0; i < 4; ++i) {
        int const a = in[i] + in[8 + i];
        int const b = in[i] - in[8 + i];
        int const cc = mul2(in[4 + i]) - mul1(in[12 + i]);
        int const dd = mul1(in[4 + i]) + mul2(in[12 + i]);
        c[i * 4 + 0] = a + dd;
        c[i * 4 + 1] = b + cc;
        c[i * 4 + 2] = b - cc;
        c[i * 4 + 3] = a - dd;
    }
    for (int i = 0; i < 4; ++i) {
        int const dc = c[i] + 4;
        int const a = dc + c[8 + i];
        int const b = dc - c[8 + i];
        int const cc = mul2(c[4 + i]) - mul1(c[12 + i]);
        int const dd = mul1(c[4 + i]) + mul2(c[12 + i]);
        std::uint8_t* row = dst + i * stride;
        row[0] = clip8(row[0] + ((a + dd) >> 3));
        row[1] = clip8(row[1] + ((b + cc) >> 3));
        row[2] = clip8(row[2] + ((b - cc) >> 3));
        row[3] = clip8(row[3] + ((a - dd) >> 3));
    }
}

bool any_nonzero(std::int16_t const* block)
{
    for (int i = 0; i < 16; ++i) {
        if (block[i] != 0)
            return true;
    }
    return false;
}

// --- Intra prediction (RFC 6386 §12), in a work area laid out as libwebp's:
// the row above (with the above-left and above-right samples) at row -1 and
// the left column at column -1, so every predictor reads its edges the same
// way wherever the block stands.
constexpr int kBps = 32;

int avg3(int a, int b, int c)
{
    return (a + 2 * b + c + 2) >> 2;
}
int avg2(int a, int b)
{
    return (a + b + 1) >> 1;
}

void predict_true_motion(std::uint8_t* dst, int size)
{
    std::uint8_t const* top = dst - kBps;
    int const top_left = top[-1];
    for (int y = 0; y < size; ++y) {
        int const left = dst[y * kBps - 1];
        for (int x = 0; x < size; ++x)
            dst[y * kBps + x] = clip8(left + top[x] - top_left);
    }
}

void predict_vertical(std::uint8_t* dst, int size)
{
    for (int y = 0; y < size; ++y)
        std::memcpy(dst + y * kBps, dst - kBps, static_cast<std::size_t>(size));
}

void predict_horizontal(std::uint8_t* dst, int size)
{
    for (int y = 0; y < size; ++y)
        std::memset(dst + y * kBps, dst[y * kBps - 1], static_cast<std::size_t>(size));
}

// DC of a 16x16 or 8x8 block: of the edges that lie inside the picture.
void predict_dc(std::uint8_t* dst, int size, bool has_top, bool has_left)
{
    int const shift = size == 16 ? 4 : 3;
    int sum = 0;
    int value;
    if (has_top && has_left) {
        for (int i = 0; i < size; ++i)
            sum += dst[i - kBps] + dst[i * kBps - 1];
        value = (sum + size) >> (shift + 1);
    } else if (has_top) {
        for (int i = 0; i < size; ++i)
            sum += dst[i - kBps];
        value = (sum + size / 2) >> shift;
    } else if (has_left) {
        for (int i = 0; i < size; ++i)
            sum += dst[i * kBps - 1];
        value = (sum + size / 2) >> shift;
    } else {
        value = 128;
    }
    for (int y = 0; y < size; ++y)
        std::memset(dst + y * kBps, value, static_cast<std::size_t>(size));
}

void predict_4x4(std::uint8_t* dst, int mode)
{
    auto D = [dst](int x, int y) -> std::uint8_t& { return dst[x + y * kBps]; };
    std::uint8_t const* top = dst - kBps;
    int const X = top[-1];
    int const A = top[0], B = top[1], C = top[2], Dd = top[3], E = top[4], F = top[5], G = top[6], H = top[7];
    int const I = dst[-1], J = dst[-1 + kBps], K = dst[-1 + 2 * kBps], L = dst[-1 + 3 * kBps];
    auto u8 = [](int v) { return static_cast<std::uint8_t>(v); };
    switch (mode) {
    case B_DC: {
        int dc = 4;
        for (int i = 0; i < 4; ++i)
            dc += top[i] + dst[i * kBps - 1];
        for (int y = 0; y < 4; ++y)
            std::memset(dst + y * kBps, dc >> 3, 4);
        break;
    }
    case B_TM:
        predict_true_motion(dst, 4);
        break;
    case B_VE: {
        std::uint8_t const values[4] = { u8(avg3(X, A, B)), u8(avg3(A, B, C)), u8(avg3(B, C, Dd)), u8(avg3(C, Dd, E)) };
        for (int y = 0; y < 4; ++y)
            std::memcpy(dst + y * kBps, values, 4);
        break;
    }
    case B_HE:
        std::memset(dst + 0 * kBps, avg3(X, I, J), 4);
        std::memset(dst + 1 * kBps, avg3(I, J, K), 4);
        std::memset(dst + 2 * kBps, avg3(J, K, L), 4);
        std::memset(dst + 3 * kBps, avg3(K, L, L), 4);
        break;
    case B_RD:
        D(0, 3) = u8(avg3(J, K, L));
        D(1, 3) = D(0, 2) = u8(avg3(I, J, K));
        D(2, 3) = D(1, 2) = D(0, 1) = u8(avg3(X, I, J));
        D(3, 3) = D(2, 2) = D(1, 1) = D(0, 0) = u8(avg3(A, X, I));
        D(3, 2) = D(2, 1) = D(1, 0) = u8(avg3(B, A, X));
        D(3, 1) = D(2, 0) = u8(avg3(C, B, A));
        D(3, 0) = u8(avg3(Dd, C, B));
        break;
    case B_LD:
        D(0, 0) = u8(avg3(A, B, C));
        D(1, 0) = D(0, 1) = u8(avg3(B, C, Dd));
        D(2, 0) = D(1, 1) = D(0, 2) = u8(avg3(C, Dd, E));
        D(3, 0) = D(2, 1) = D(1, 2) = D(0, 3) = u8(avg3(Dd, E, F));
        D(3, 1) = D(2, 2) = D(1, 3) = u8(avg3(E, F, G));
        D(3, 2) = D(2, 3) = u8(avg3(F, G, H));
        D(3, 3) = u8(avg3(G, H, H));
        break;
    case B_VR:
        D(0, 0) = D(1, 2) = u8(avg2(X, A));
        D(1, 0) = D(2, 2) = u8(avg2(A, B));
        D(2, 0) = D(3, 2) = u8(avg2(B, C));
        D(3, 0) = u8(avg2(C, Dd));
        D(0, 3) = u8(avg3(K, J, I));
        D(0, 2) = u8(avg3(J, I, X));
        D(0, 1) = D(1, 3) = u8(avg3(I, X, A));
        D(1, 1) = D(2, 3) = u8(avg3(X, A, B));
        D(2, 1) = D(3, 3) = u8(avg3(A, B, C));
        D(3, 1) = u8(avg3(B, C, Dd));
        break;
    case B_VL:
        D(0, 0) = u8(avg2(A, B));
        D(1, 0) = D(0, 2) = u8(avg2(B, C));
        D(2, 0) = D(1, 2) = u8(avg2(C, Dd));
        D(3, 0) = D(2, 2) = u8(avg2(Dd, E));
        D(0, 1) = u8(avg3(A, B, C));
        D(1, 1) = D(0, 3) = u8(avg3(B, C, Dd));
        D(2, 1) = D(1, 3) = u8(avg3(C, Dd, E));
        D(3, 1) = D(2, 3) = u8(avg3(Dd, E, F));
        D(3, 2) = u8(avg3(E, F, G));
        D(3, 3) = u8(avg3(F, G, H));
        break;
    case B_HD:
        D(0, 0) = D(2, 1) = u8(avg2(I, X));
        D(0, 1) = D(2, 2) = u8(avg2(J, I));
        D(0, 2) = D(2, 3) = u8(avg2(K, J));
        D(0, 3) = u8(avg2(L, K));
        D(3, 0) = u8(avg3(A, B, C));
        D(2, 0) = u8(avg3(X, A, B));
        D(1, 0) = D(3, 1) = u8(avg3(I, X, A));
        D(1, 1) = D(3, 2) = u8(avg3(J, I, X));
        D(1, 2) = D(3, 3) = u8(avg3(K, J, I));
        D(1, 3) = u8(avg3(L, K, J));
        break;
    case B_HU:
        D(0, 0) = u8(avg2(I, J));
        D(2, 0) = D(0, 1) = u8(avg2(J, K));
        D(2, 1) = D(0, 2) = u8(avg2(K, L));
        D(1, 0) = u8(avg3(I, J, K));
        D(3, 0) = D(1, 1) = u8(avg3(J, K, L));
        D(3, 1) = D(1, 2) = u8(avg3(K, L, L));
        D(3, 2) = D(2, 2) = D(0, 3) = D(1, 3) = D(2, 3) = D(3, 3) = u8(L);
        break;
    default:
        break;
    }
}

// --- The loop filter (RFC 6386 §15), as libwebp writes it.
int sclip1(int v)
{
    return v < -128 ? -128 : v > 127 ? 127 : v;
}
int sclip2(int v)
{
    return v < -16 ? -16 : v > 15 ? 15 : v;
}

void filter2(std::uint8_t* p, int step)
{
    int const p1 = p[-2 * step], p0 = p[-step], q0 = p[0], q1 = p[step];
    int const a = 3 * (q0 - p0) + sclip1(p1 - q1);
    int const a1 = sclip2((a + 4) >> 3);
    int const a2 = sclip2((a + 3) >> 3);
    p[-step] = clip8(p0 + a2);
    p[0] = clip8(q0 - a1);
}

void filter4(std::uint8_t* p, int step)
{
    int const p1 = p[-2 * step], p0 = p[-step], q0 = p[0], q1 = p[step];
    int const a = 3 * (q0 - p0);
    int const a1 = sclip2((a + 4) >> 3);
    int const a2 = sclip2((a + 3) >> 3);
    int const a3 = (a1 + 1) >> 1;
    p[-2 * step] = clip8(p1 + a3);
    p[-step] = clip8(p0 + a2);
    p[0] = clip8(q0 - a1);
    p[step] = clip8(q1 - a3);
}

void filter6(std::uint8_t* p, int step)
{
    int const p2 = p[-3 * step], p1 = p[-2 * step], p0 = p[-step];
    int const q0 = p[0], q1 = p[step], q2 = p[2 * step];
    int const a = sclip1(3 * (q0 - p0) + sclip1(p1 - q1));
    int const a1 = (27 * a + 63) >> 7;
    int const a2 = (18 * a + 63) >> 7;
    int const a3 = (9 * a + 63) >> 7;
    p[-3 * step] = clip8(p2 + a3);
    p[-2 * step] = clip8(p1 + a2);
    p[-step] = clip8(p0 + a1);
    p[0] = clip8(q0 - a1);
    p[step] = clip8(q1 - a2);
    p[2 * step] = clip8(q2 - a3);
}

bool high_edge_variance(std::uint8_t const* p, int step, int threshold)
{
    int const p1 = p[-2 * step], p0 = p[-step], q0 = p[0], q1 = p[step];
    return std::abs(p1 - p0) > threshold || std::abs(q1 - q0) > threshold;
}

bool needs_filter(std::uint8_t const* p, int step, int t)
{
    int const p1 = p[-2 * step], p0 = p[-step], q0 = p[0], q1 = p[step];
    return 4 * std::abs(p0 - q0) + std::abs(p1 - q1) <= t;
}

bool needs_filter2(std::uint8_t const* p, int step, int t, int it)
{
    int const p3 = p[-4 * step], p2 = p[-3 * step], p1 = p[-2 * step], p0 = p[-step];
    int const q0 = p[0], q1 = p[step], q2 = p[2 * step], q3 = p[3 * step];
    if (4 * std::abs(p0 - q0) + std::abs(p1 - q1) > t)
        return false;
    return std::abs(p3 - p2) <= it && std::abs(p2 - p1) <= it && std::abs(p1 - p0) <= it && std::abs(q3 - q2) <= it
        && std::abs(q2 - q1) <= it && std::abs(q1 - q0) <= it;
}

// Across `count` positions spaced `along`, the edge crossed by `across`.
void filter_simple_edge(std::uint8_t* p, int across, int along, int count, int threshold)
{
    int const t = 2 * threshold + 1;
    for (int i = 0; i < count; ++i, p += along) {
        if (needs_filter(p, across, t))
            filter2(p, across);
    }
}

void filter_edge(std::uint8_t* p, int across, int along, int count, int threshold, int interior, int hev, bool macroblock_edge)
{
    int const t = 2 * threshold + 1;
    for (int i = 0; i < count; ++i, p += along) {
        if (!needs_filter2(p, across, t, interior))
            continue;
        if (high_edge_variance(p, across, hev))
            filter2(p, across);
        else if (macroblock_edge)
            filter6(p, across);
        else
            filter4(p, across);
    }
}

// --- YUV to RGB, as libwebp converts (14-bit fixed point), with the chroma
// upsampled by its "fancy" filter: each chroma sample spread over the two
// rows and columns around it with weights 9-3-3-1.
int yuv_clip(int v)
{
    return (v & ~16383) == 0 ? (v >> 6) : v < 0 ? 0 : 255;
}
int mult_hi(int v, int coefficient)
{
    return (v * coefficient) >> 8;
}
void yuv_to_rgb(int y, int u, int v, std::uint8_t* rgba)
{
    rgba[0] = static_cast<std::uint8_t>(yuv_clip(mult_hi(y, 19077) + mult_hi(v, 26149) - 14234));
    rgba[1] = static_cast<std::uint8_t>(yuv_clip(mult_hi(y, 19077) - mult_hi(u, 6419) - mult_hi(v, 13320) + 8708));
    rgba[2] = static_cast<std::uint8_t>(yuv_clip(mult_hi(y, 19077) + mult_hi(u, 33050) - 17685));
}

// One or two output rows from the chroma rows above and below them.
void upsample_rows(std::uint8_t const* top_y, std::uint8_t const* bottom_y, std::uint8_t const* top_u,
    std::uint8_t const* top_v, std::uint8_t const* cur_u, std::uint8_t const* cur_v, std::uint8_t* top_dst,
    std::uint8_t* bottom_dst, int len)
{
    auto const load = [](std::uint8_t u, std::uint8_t v) { return static_cast<std::uint32_t>(u) | (static_cast<std::uint32_t>(v) << 16); };
    auto const emit = [](std::uint8_t y, std::uint32_t uv, std::uint8_t* dst) {
        yuv_to_rgb(y, static_cast<int>(uv & 0xff), static_cast<int>(uv >> 16), dst);
    };
    int const last_pair = (len - 1) >> 1;
    std::uint32_t tl_uv = load(top_u[0], top_v[0]);
    std::uint32_t l_uv = load(cur_u[0], cur_v[0]);
    emit(top_y[0], (3 * tl_uv + l_uv + 0x00020002u) >> 2, top_dst);
    if (bottom_y)
        emit(bottom_y[0], (3 * l_uv + tl_uv + 0x00020002u) >> 2, bottom_dst);
    for (int x = 1; x <= last_pair; ++x) {
        std::uint32_t const t_uv = load(top_u[x], top_v[x]);
        std::uint32_t const uv = load(cur_u[x], cur_v[x]);
        std::uint32_t const avg = tl_uv + t_uv + l_uv + uv + 0x00080008u;
        std::uint32_t const diag_12 = (avg + 2 * (t_uv + l_uv)) >> 3;
        std::uint32_t const diag_03 = (avg + 2 * (tl_uv + uv)) >> 3;
        emit(top_y[2 * x - 1], (diag_12 + tl_uv) >> 1, top_dst + (2 * x - 1) * 4);
        emit(top_y[2 * x], (diag_03 + t_uv) >> 1, top_dst + (2 * x) * 4);
        if (bottom_y) {
            emit(bottom_y[2 * x - 1], (diag_03 + l_uv) >> 1, bottom_dst + (2 * x - 1) * 4);
            emit(bottom_y[2 * x], (diag_12 + uv) >> 1, bottom_dst + (2 * x) * 4);
        }
        tl_uv = t_uv;
        l_uv = uv;
    }
    if (!(len & 1)) {
        emit(top_y[len - 1], (3 * tl_uv + l_uv + 0x00020002u) >> 2, top_dst + (len - 1) * 4);
        if (bottom_y)
            emit(bottom_y[len - 1], (3 * l_uv + tl_uv + 0x00020002u) >> 2, bottom_dst + (len - 1) * 4);
    }
}

// The decoded planes as RGBA, opaque.
std::vector<std::uint8_t> planes_to_rgba(Planes const& planes)
{
    int const w = planes.width, h = planes.height;
    std::vector<std::uint8_t> rgba(static_cast<std::size_t>(w) * static_cast<std::size_t>(h) * 4, 255);
    auto const yrow = [&](int y) { return planes.y.data() + static_cast<std::size_t>(y) * static_cast<std::size_t>(planes.y_stride); };
    auto const urow = [&](int y) { return planes.u.data() + static_cast<std::size_t>(y) * static_cast<std::size_t>(planes.uv_stride); };
    auto const vrow = [&](int y) { return planes.v.data() + static_cast<std::size_t>(y) * static_cast<std::size_t>(planes.uv_stride); };
    auto const out = [&](int y) { return rgba.data() + static_cast<std::size_t>(y) * static_cast<std::size_t>(w) * 4; };
    // The first row against its own chroma row, mirrored; then each pair of
    // rows between two chroma rows; and the last row of an even height alone.
    upsample_rows(yrow(0), nullptr, urow(0), vrow(0), urow(0), vrow(0), out(0), nullptr, w);
    int y = 1;
    for (; y + 1 < h; y += 2) {
        int const top_uv = (y - 1) / 2;
        upsample_rows(yrow(y), yrow(y + 1), urow(top_uv), vrow(top_uv), urow(top_uv + 1), vrow(top_uv + 1), out(y),
            out(y + 1), w);
    }
    if (y < h) {
        int const last_uv = (h - 1) / 2;
        upsample_rows(yrow(y), nullptr, urow(last_uv), vrow(last_uv), urow(last_uv), vrow(last_uv), out(y), nullptr, w);
    }
    return rgba;
}

// A VP8 key frame (RFC 6386) into its Y, U and V planes.
std::optional<Planes> decode_vp8(std::uint8_t const* data, std::size_t size, std::size_t max_pixels)
{
    if (size < 10)
        return std::nullopt;
    std::uint32_t const tag = data[0] | (data[1] << 8) | (data[2] << 16);
    bool const key_frame = !(tag & 1);
    std::uint32_t const first_size = tag >> 5;
    if (!key_frame || data[3] != 0x9d || data[4] != 0x01 || data[5] != 0x2a)
        return std::nullopt;
    int const width = (data[6] | (data[7] << 8)) & 0x3fff;
    int const height = (data[8] | (data[9] << 8)) & 0x3fff;
    if (width == 0 || height == 0
        || static_cast<std::size_t>(width) * static_cast<std::size_t>(height) > max_pixels)
        return std::nullopt;
    data += 10;
    size -= 10;
    if (first_size > size)
        return std::nullopt;
    BoolDecoder header(data, first_size);
    header.literal(2); // colour space and clamping: every value is clamped either way

    // Segments (§9.3).
    bool const segmented = header.read(128);
    bool update_map = false;
    bool absolute_values = true;
    int segment_quant[4] = {};
    int segment_filter[4] = {};
    std::uint8_t segment_probs[3] = { 255, 255, 255 };
    if (segmented) {
        update_map = header.read(128);
        if (header.read(128)) {
            absolute_values = header.read(128);
            for (int& q : segment_quant)
                q = header.optional_signed(7);
            for (int& f : segment_filter)
                f = header.optional_signed(6);
        }
        if (update_map) {
            for (std::uint8_t& p : segment_probs)
                p = static_cast<std::uint8_t>(header.read(128) ? header.literal(8) : 255);
        }
    }
    // The loop filter (§9.6).
    bool const simple_filter = header.read(128);
    int const filter_level = header.literal(6);
    int const sharpness = header.literal(3);
    int ref_delta = 0, mode_delta = 0; // intra frames read the first of each
    bool const use_deltas = header.read(128);
    if (use_deltas && header.read(128)) {
        for (int i = 0; i < 4; ++i) {
            if (header.read(128)) {
                int const v = header.signed_literal(6);
                if (i == 0)
                    ref_delta = v;
            }
        }
        for (int i = 0; i < 4; ++i) {
            if (header.read(128)) {
                int const v = header.signed_literal(6);
                if (i == 0)
                    mode_delta = v;
            }
        }
    }
    // The token partitions (§9.5).
    int const partition_count = 1 << header.literal(2);
    std::uint8_t const* sizes = data + first_size;
    std::size_t left = size - first_size;
    std::size_t const table = 3u * static_cast<std::size_t>(partition_count - 1);
    if (left < table)
        return std::nullopt;
    std::uint8_t const* part = sizes + table;
    left -= table;
    std::vector<BoolDecoder> partitions;
    for (int p = 0; p < partition_count - 1; ++p) {
        std::size_t part_size = sizes[3 * p] | (sizes[3 * p + 1] << 8) | (sizes[3 * p + 2] << 16);
        part_size = std::min(part_size, left);
        partitions.emplace_back(part, part_size);
        part += part_size;
        left -= part_size;
    }
    partitions.emplace_back(part, left);
    // The quantizers (§9.6, §14.1).
    int const base_q = header.literal(7);
    int const y1_dc_delta = header.optional_signed(4);
    int const y2_dc_delta = header.optional_signed(4);
    int const y2_ac_delta = header.optional_signed(4);
    int const uv_dc_delta = header.optional_signed(4);
    int const uv_ac_delta = header.optional_signed(4);
    Quant quants[4];
    for (int s = 0; s < 4; ++s) {
        int q = base_q;
        if (segmented)
            q = absolute_values ? segment_quant[s] : base_q + segment_quant[s];
        auto const index = [](int v, int high) { return v < 0 ? 0 : v > high ? high : v; };
        Quant& m = quants[s];
        m.y1_dc = kDcTable[index(q + y1_dc_delta, 127)];
        m.y1_ac = kAcTable[index(q, 127)];
        m.y2_dc = kDcTable[index(q + y2_dc_delta, 127)] * 2;
        m.y2_ac = std::max(8, (kAcTable[index(q + y2_ac_delta, 127)] * 101581) >> 16);
        m.uv_dc = kDcTable[index(q + uv_dc_delta, 117)];
        m.uv_ac = kAcTable[index(q + uv_ac_delta, 127)];
    }
    header.read(128); // refresh the entropy probabilities: one frame, nothing to keep
    CoeffProbs probs;
    for (int t = 0; t < 4; ++t)
        for (int b = 0; b < 8; ++b)
            for (int c = 0; c < 3; ++c)
                for (int p = 0; p < 11; ++p)
                    probs[t][b][c][p] = static_cast<std::uint8_t>(
                        header.read(kCoeffUpdateProbs[t][b][c][p]) ? header.literal(8) : kDefaultCoeffProbs[t][b][c][p]);
    bool const use_skip = header.read(128);
    int const skip_probability = use_skip ? header.literal(8) : 0;

    // Filter strengths by segment and kind of macroblock (§15.1, §9.6).
    FilterInfo strengths[4][2];
    for (int s = 0; s < 4; ++s) {
        int base_level = filter_level;
        if (segmented)
            base_level = absolute_values ? segment_filter[s] : filter_level + segment_filter[s];
        for (int i4x4 = 0; i4x4 <= 1; ++i4x4) {
            FilterInfo& info = strengths[s][i4x4];
            int level = base_level;
            if (use_deltas) {
                level += ref_delta;
                if (i4x4)
                    level += mode_delta;
            }
            level = std::clamp(level, 0, 63);
            if (level > 0 && filter_level > 0) {
                int interior = level;
                if (sharpness > 0) {
                    interior >>= sharpness > 4 ? 2 : 1;
                    interior = std::min(interior, 9 - sharpness);
                }
                interior = std::max(interior, 1);
                info.interior = interior;
                info.limit = 2 * level + interior;
                info.hev_threshold = level >= 40 ? 2 : level >= 15 ? 1 : 0;
            }
        }
    }

    int const mb_w = (width + 15) / 16;
    int const mb_h = (height + 15) / 16;
    Planes planes;
    planes.width = width;
    planes.height = height;
    planes.y_stride = mb_w * 16;
    planes.uv_stride = mb_w * 8;
    planes.y.assign(static_cast<std::size_t>(planes.y_stride) * static_cast<std::size_t>(mb_h) * 16, 0);
    planes.u.assign(static_cast<std::size_t>(planes.uv_stride) * static_cast<std::size_t>(mb_h) * 8, 0);
    planes.v.assign(planes.u.size(), 0);
    std::vector<FilterInfo> filters(static_cast<std::size_t>(mb_w) * static_cast<std::size_t>(mb_h));
    std::vector<std::array<std::uint8_t, 4>> top_modes(static_cast<std::size_t>(mb_w), { B_DC, B_DC, B_DC, B_DC });
    std::vector<NonZero> top_nz(static_cast<std::size_t>(mb_w));

    // The work area: luma at rows 1..16, columns 1..20 of a 32-wide grid
    // (row 0 the edge above, column 0 the edge to the left), chroma beside.
    std::array<std::uint8_t, kBps * 17> ywork {};
    std::array<std::uint8_t, kBps * 9> uwork {};
    std::array<std::uint8_t, kBps * 9> vwork {};
    std::uint8_t* const ydst = ywork.data() + kBps + 1;
    std::uint8_t* const udst = uwork.data() + kBps + 1;
    std::uint8_t* const vdst = vwork.data() + kBps + 1;

    for (int mb_y = 0; mb_y < mb_h; ++mb_y) {
        std::array<std::uint8_t, 4> left_modes = { B_DC, B_DC, B_DC, B_DC };
        NonZero left_nz;
        BoolDecoder& tokens = partitions[static_cast<std::size_t>(mb_y & (partition_count - 1))];
        for (int mb_x = 0; mb_x < mb_w; ++mb_x) {
            // The macroblock's header (§19.3).
            int segment = 0;
            if (update_map)
                segment = !header.read(segment_probs[0]) ? header.read(segment_probs[1]) : 2 + header.read(segment_probs[2]);
            bool const skip = use_skip && header.read(skip_probability);
            bool const i4x4 = !header.read(145);
            std::array<std::uint8_t, 16> sub_modes {};
            int y_mode = DC_PRED;
            std::array<std::uint8_t, 4>& above = top_modes[static_cast<std::size_t>(mb_x)];
            if (!i4x4) {
                y_mode = header.read(156) ? (header.read(128) ? TM_PRED : H_PRED) : (header.read(163) ? V_PRED : DC_PRED);
                above.fill(static_cast<std::uint8_t>(y_mode));
                left_modes.fill(static_cast<std::uint8_t>(y_mode));
            } else {
                for (int y = 0; y < 4; ++y) {
                    int mode = left_modes[static_cast<std::size_t>(y)];
                    for (int x = 0; x < 4; ++x) {
                        mode = header.tree(kBModeTree, kBModeProbs[above[static_cast<std::size_t>(x)]][mode]);
                        above[static_cast<std::size_t>(x)] = static_cast<std::uint8_t>(mode);
                        sub_modes[static_cast<std::size_t>(y * 4 + x)] = static_cast<std::uint8_t>(mode);
                    }
                    left_modes[static_cast<std::size_t>(y)] = static_cast<std::uint8_t>(mode);
                }
            }
            int const uv_mode = !header.read(142) ? DC_PRED : !header.read(114) ? V_PRED : header.read(183) ? TM_PRED : H_PRED;

            // Its tokens (§13).
            std::array<std::int16_t, 24 * 16> coeffs {};
            NonZero& tnz = top_nz[static_cast<std::size_t>(mb_x)];
            Quant const& q = quants[segment];
            bool has_coefficients = false;
            if (!skip) {
                int first = 0;
                std::uint8_t const (*y_bands)[3][11] = probs[3];
                if (!i4x4) {
                    std::array<std::int16_t, 16> y2 {};
                    int const nz = read_coefficients(tokens, probs[1], tnz.y2 + left_nz.y2, 0, q.y2_dc, q.y2_ac, y2.data());
                    tnz.y2 = left_nz.y2 = nz > 0;
                    if (nz > 1) {
                        inverse_wht(y2.data(), coeffs.data());
                    } else {
                        std::int16_t const dc0 = static_cast<std::int16_t>((y2[0] + 3) >> 3);
                        for (int b = 0; b < 16; ++b)
                            coeffs[static_cast<std::size_t>(b * 16)] = dc0;
                    }
                    first = 1;
                    y_bands = probs[0];
                }
                for (int y = 0; y < 4; ++y) {
                    for (int x = 0; x < 4; ++x) {
                        std::int16_t* block = coeffs.data() + (y * 4 + x) * 16;
                        int const nz = read_coefficients(tokens, y_bands, tnz.y[x] + left_nz.y[y], first, q.y1_dc, q.y1_ac, block);
                        tnz.y[x] = left_nz.y[y] = nz > first;
                    }
                }
                for (int plane = 0; plane < 2; ++plane) {
                    std::uint8_t* const t = plane == 0 ? tnz.u : tnz.v;
                    std::uint8_t* const l = plane == 0 ? left_nz.u : left_nz.v;
                    for (int y = 0; y < 2; ++y) {
                        for (int x = 0; x < 2; ++x) {
                            std::int16_t* block = coeffs.data() + (16 + plane * 4 + y * 2 + x) * 16;
                            int const nz = read_coefficients(tokens, probs[2], t[x] + l[y], 0, q.uv_dc, q.uv_ac, block);
                            t[x] = l[y] = nz > 0;
                        }
                    }
                }
                for (int b = 0; b < 24 && !has_coefficients; ++b)
                    has_coefficients = any_nonzero(coeffs.data() + b * 16);
            } else {
                tnz.y[0] = tnz.y[1] = tnz.y[2] = tnz.y[3] = 0;
                tnz.u[0] = tnz.u[1] = tnz.v[0] = tnz.v[1] = 0;
                left_nz.y[0] = left_nz.y[1] = left_nz.y[2] = left_nz.y[3] = 0;
                left_nz.u[0] = left_nz.u[1] = left_nz.v[0] = left_nz.v[1] = 0;
                if (!i4x4)
                    tnz.y2 = left_nz.y2 = 0;
            }
            FilterInfo& filter = filters[static_cast<std::size_t>(mb_y) * static_cast<std::size_t>(mb_w) + static_cast<std::size_t>(mb_x)];
            filter = strengths[segment][i4x4 ? 1 : 0];
            filter.inner = i4x4 || has_coefficients;

            // The edges around it, into the work area (§12.2): above the
            // picture 127, left of it 129; the above-right of the last
            // column repeats the last above sample.
            std::uint8_t* const yplane = planes.y.data();
            std::uint8_t* const uplane = planes.u.data();
            std::uint8_t* const vplane = planes.v.data();
            std::size_t const ys = static_cast<std::size_t>(planes.y_stride);
            std::size_t const us = static_cast<std::size_t>(planes.uv_stride);
            std::size_t const x0 = static_cast<std::size_t>(mb_x) * 16, y0 = static_cast<std::size_t>(mb_y) * 16;
            std::size_t const cx0 = static_cast<std::size_t>(mb_x) * 8, cy0 = static_cast<std::size_t>(mb_y) * 8;
            if (mb_y == 0) {
                std::memset(ydst - kBps - 1, 127, 21);
                std::memset(udst - kBps - 1, 127, 9);
                std::memset(vdst - kBps - 1, 127, 9);
            } else {
                std::uint8_t const* above_y = yplane + (y0 - 1) * ys + x0;
                std::memcpy(ydst - kBps, above_y, 16);
                if (mb_x + 1 < mb_w)
                    std::memcpy(ydst - kBps + 16, above_y + 16, 4);
                else
                    std::memset(ydst - kBps + 16, above_y[15], 4);
                std::memcpy(udst - kBps, uplane + (cy0 - 1) * us + cx0, 8);
                std::memcpy(vdst - kBps, vplane + (cy0 - 1) * us + cx0, 8);
                if (mb_x == 0) {
                    ydst[-kBps - 1] = 129;
                    udst[-kBps - 1] = 129;
                    vdst[-kBps - 1] = 129;
                } else {
                    ydst[-kBps - 1] = above_y[-1];
                    udst[-kBps - 1] = uplane[(cy0 - 1) * us + cx0 - 1];
                    vdst[-kBps - 1] = vplane[(cy0 - 1) * us + cx0 - 1];
                }
            }
            for (int r = 0; r < 16; ++r)
                ydst[r * kBps - 1] = mb_x == 0 ? 129 : yplane[(y0 + static_cast<std::size_t>(r)) * ys + x0 - 1];
            for (int r = 0; r < 8; ++r) {
                udst[r * kBps - 1] = mb_x == 0 ? 129 : uplane[(cy0 + static_cast<std::size_t>(r)) * us + cx0 - 1];
                vdst[r * kBps - 1] = mb_x == 0 ? 129 : vplane[(cy0 + static_cast<std::size_t>(r)) * us + cx0 - 1];
            }
            // The 4x4 blocks of the right column read the macroblock's
            // above-right samples on every row.
            for (int r = 3; r < 16; r += 4)
                std::memcpy(ydst + r * kBps + 16, ydst - kBps + 16, 4);

            // Prediction and residue (§12, §14).
            if (i4x4) {
                for (int b = 0; b < 16; ++b) {
                    std::uint8_t* dst = ydst + (b / 4) * 4 * kBps + (b % 4) * 4;
                    predict_4x4(dst, sub_modes[static_cast<std::size_t>(b)]);
                    if (any_nonzero(coeffs.data() + b * 16))
                        add_inverse_dct(coeffs.data() + b * 16, dst, kBps);
                }
            } else {
                switch (y_mode) {
                case DC_PRED: predict_dc(ydst, 16, mb_y > 0, mb_x > 0); break;
                case TM_PRED: predict_true_motion(ydst, 16); break;
                case V_PRED: predict_vertical(ydst, 16); break;
                default: predict_horizontal(ydst, 16); break;
                }
                for (int b = 0; b < 16; ++b) {
                    if (any_nonzero(coeffs.data() + b * 16))
                        add_inverse_dct(coeffs.data() + b * 16, ydst + (b / 4) * 4 * kBps + (b % 4) * 4, kBps);
                }
            }
            for (int plane = 0; plane < 2; ++plane) {
                std::uint8_t* const dst = plane == 0 ? udst : vdst;
                switch (uv_mode) {
                case DC_PRED: predict_dc(dst, 8, mb_y > 0, mb_x > 0); break;
                case TM_PRED: predict_true_motion(dst, 8); break;
                case V_PRED: predict_vertical(dst, 8); break;
                default: predict_horizontal(dst, 8); break;
                }
                for (int b = 0; b < 4; ++b) {
                    std::int16_t const* block = coeffs.data() + (16 + plane * 4 + b) * 16;
                    if (any_nonzero(block))
                        add_inverse_dct(block, dst + (b / 2) * 4 * kBps + (b % 2) * 4, kBps);
                }
            }
            for (int r = 0; r < 16; ++r)
                std::memcpy(yplane + (y0 + static_cast<std::size_t>(r)) * ys + x0, ydst + r * kBps, 16);
            for (int r = 0; r < 8; ++r) {
                std::memcpy(uplane + (cy0 + static_cast<std::size_t>(r)) * us + cx0, udst + r * kBps, 8);
                std::memcpy(vplane + (cy0 + static_cast<std::size_t>(r)) * us + cx0, vdst + r * kBps, 8);
            }
        }
        if (header.overrun() || tokens.overrun())
            return std::nullopt;
    }

    // The loop filter over the whole frame, macroblock by macroblock in
    // raster order: the left edge, the inner vertical edges, the top edge,
    // the inner horizontal edges (§15.2).
    if (filter_level > 0) {
        int const ys = planes.y_stride, us = planes.uv_stride;
        for (int mb_y = 0; mb_y < mb_h; ++mb_y) {
            for (int mb_x = 0; mb_x < mb_w; ++mb_x) {
                FilterInfo const& f = filters[static_cast<std::size_t>(mb_y) * static_cast<std::size_t>(mb_w) + static_cast<std::size_t>(mb_x)];
                if (f.limit == 0)
                    continue;
                std::uint8_t* const y = planes.y.data() + static_cast<std::size_t>(mb_y) * 16 * static_cast<std::size_t>(ys) + static_cast<std::size_t>(mb_x) * 16;
                std::uint8_t* const u = planes.u.data() + static_cast<std::size_t>(mb_y) * 8 * static_cast<std::size_t>(us) + static_cast<std::size_t>(mb_x) * 8;
                std::uint8_t* const v = planes.v.data() + static_cast<std::size_t>(mb_y) * 8 * static_cast<std::size_t>(us) + static_cast<std::size_t>(mb_x) * 8;
                if (simple_filter) {
                    if (mb_x > 0)
                        filter_simple_edge(y, 1, ys, 16, f.limit + 4);
                    if (f.inner)
                        for (int k = 4; k < 16; k += 4)
                            filter_simple_edge(y + k, 1, ys, 16, f.limit);
                    if (mb_y > 0)
                        filter_simple_edge(y, ys, 1, 16, f.limit + 4);
                    if (f.inner)
                        for (int k = 4; k < 16; k += 4)
                            filter_simple_edge(y + k * ys, ys, 1, 16, f.limit);
                    continue;
                }
                int const it = f.interior, hev = f.hev_threshold;
                if (mb_x > 0) {
                    filter_edge(y, 1, ys, 16, f.limit + 4, it, hev, true);
                    filter_edge(u, 1, us, 8, f.limit + 4, it, hev, true);
                    filter_edge(v, 1, us, 8, f.limit + 4, it, hev, true);
                }
                if (f.inner) {
                    for (int k = 4; k < 16; k += 4)
                        filter_edge(y + k, 1, ys, 16, f.limit, it, hev, false);
                    filter_edge(u + 4, 1, us, 8, f.limit, it, hev, false);
                    filter_edge(v + 4, 1, us, 8, f.limit, it, hev, false);
                }
                if (mb_y > 0) {
                    filter_edge(y, ys, 1, 16, f.limit + 4, it, hev, true);
                    filter_edge(u, us, 1, 8, f.limit + 4, it, hev, true);
                    filter_edge(v, us, 1, 8, f.limit + 4, it, hev, true);
                }
                if (f.inner) {
                    for (int k = 4; k < 16; k += 4)
                        filter_edge(y + k * ys, ys, 1, 16, f.limit, it, hev, false);
                    filter_edge(u + 4 * us, us, 1, 8, f.limit, it, hev, false);
                    filter_edge(v + 4 * us, us, 1, 8, f.limit, it, hev, false);
                }
            }
        }
    }
    return planes;
}

