// The entropy-coded pixels of one image of the stream (§5.2), with the
// colour cache and, for the main image, the meta prefix codes.
std::optional<std::vector<std::uint32_t>> decode_pixels(LsbReader& r, int width, int height, bool main_image,
    std::size_t max_pixels)
{
    int cache_bits = 0;
    if (r.read(1)) {
        cache_bits = static_cast<int>(r.read(4));
        if (cache_bits < 1 || cache_bits > 11)
            return std::nullopt;
    }
    int meta_bits = 0;
    std::vector<std::uint32_t> meta;
    int meta_width = 0;
    int groups = 1;
    if (main_image && r.read(1)) {
        meta_bits = static_cast<int>(r.read(3)) + 2;
        meta_width = (width + (1 << meta_bits) - 1) >> meta_bits;
        int const meta_height = (height + (1 << meta_bits) - 1) >> meta_bits;
        std::optional<std::vector<std::uint32_t>> image = decode_image_stream(r, meta_width, meta_height, false, max_pixels);
        if (!image)
            return std::nullopt;
        meta = std::move(*image);
        for (std::uint32_t& m : meta) {
            m = (m >> 8) & 0xffff;
            groups = std::max(groups, static_cast<int>(m) + 1);
        }
    }
    int const cache_size = cache_bits ? 1 << cache_bits : 0;
    std::vector<CodeGroup> codes;
    codes.reserve(static_cast<std::size_t>(groups));
    for (int g = 0; g < groups; ++g) {
        CodeGroup group;
        std::optional<PrefixCode> green = read_prefix_code(r, 256 + 24 + cache_size);
        std::optional<PrefixCode> red = green ? read_prefix_code(r, 256) : std::nullopt;
        std::optional<PrefixCode> blue = red ? read_prefix_code(r, 256) : std::nullopt;
        std::optional<PrefixCode> alpha = blue ? read_prefix_code(r, 256) : std::nullopt;
        std::optional<PrefixCode> distance = alpha ? read_prefix_code(r, 40) : std::nullopt;
        if (!distance || r.overrun())
            return std::nullopt;
        group.green = std::move(*green);
        group.red = std::move(*red);
        group.blue = std::move(*blue);
        group.alpha = std::move(*alpha);
        group.distance = std::move(*distance);
        codes.push_back(std::move(group));
    }
    std::size_t const total = static_cast<std::size_t>(width) * static_cast<std::size_t>(height);
    std::vector<std::uint32_t> pixels(total, 0);
    std::vector<std::uint32_t> cache(static_cast<std::size_t>(cache_size), 0);
    auto const remember = [&](std::uint32_t argb) {
        if (cache_size)
            cache[(0x1e35a7bdu * argb) >> (32 - cache_bits)] = argb;
    };
    std::size_t pos = 0;
    int x = 0, y = 0;
    auto const group_at = [&]() -> CodeGroup const& {
        if (meta.empty())
            return codes[0];
        return codes[meta[static_cast<std::size_t>(y >> meta_bits) * static_cast<std::size_t>(meta_width)
            + static_cast<std::size_t>(x >> meta_bits)]];
    };
    auto const advance = [&] {
        if (++x == width) {
            x = 0;
            ++y;
        }
    };
    while (pos < total) {
        CodeGroup const& group = group_at();
        int const code = group.green.read(r);
        if (code < 0 || r.overrun())
            return std::nullopt;
        if (code < 256) {
            std::uint32_t const red = static_cast<std::uint32_t>(group.red.read(r));
            std::uint32_t const blue = static_cast<std::uint32_t>(group.blue.read(r));
            std::uint32_t const alpha = static_cast<std::uint32_t>(group.alpha.read(r));
            std::uint32_t const argb = (alpha << 24) | (red << 16) | (static_cast<std::uint32_t>(code) << 8) | blue;
            pixels[pos++] = argb;
            remember(argb);
            advance();
        } else if (code < 256 + 24) {
            std::uint32_t const length = prefix_value(r, code - 256);
            int const distance_symbol = group.distance.read(r);
            if (distance_symbol < 0)
                return std::nullopt;
            std::uint32_t const distance_code = prefix_value(r, distance_symbol);
            std::size_t distance;
            if (distance_code > 120) {
                distance = distance_code - 120;
            } else {
                std::int8_t const* offset = kDistanceMap[distance_code - 1];
                long const d = offset[0] + static_cast<long>(offset[1]) * width;
                distance = d < 1 ? 1 : static_cast<std::size_t>(d);
            }
            if (distance > pos || length > total - pos)
                return std::nullopt;
            for (std::uint32_t i = 0; i < length; ++i) {
                std::uint32_t const argb = pixels[pos - distance];
                pixels[pos++] = argb;
                remember(argb);
                advance();
            }
        } else {
            int const index = code - 280;
            if (index >= cache_size)
                return std::nullopt;
            std::uint32_t const argb = cache[static_cast<std::size_t>(index)];
            pixels[pos++] = argb;
            remember(argb);
            advance();
        }
    }
    if (r.overrun())
        return std::nullopt;
    return pixels;
}

std::uint32_t add_pixels(std::uint32_t a, std::uint32_t b)
{
    std::uint32_t const alpha_green = (a & 0xff00ff00u) + (b & 0xff00ff00u);
    std::uint32_t const red_blue = (a & 0x00ff00ffu) + (b & 0x00ff00ffu);
    return (alpha_green & 0xff00ff00u) | (red_blue & 0x00ff00ffu);
}

std::uint32_t average2(std::uint32_t a, std::uint32_t b)
{
    return (((a ^ b) & 0xfefefefeu) >> 1) + (a & b);
}

int channel(std::uint32_t argb, int shift)
{
    return static_cast<int>((argb >> shift) & 0xff);
}

std::uint32_t select_predictor(std::uint32_t left, std::uint32_t top, std::uint32_t top_left)
{
    int distance_left = 0, distance_top = 0; // to the estimate L + T - TL
    for (int shift = 0; shift < 32; shift += 8) {
        int const estimate = channel(left, shift) + channel(top, shift) - channel(top_left, shift);
        distance_left += std::abs(estimate - channel(left, shift));
        distance_top += std::abs(estimate - channel(top, shift));
    }
    return distance_left < distance_top ? left : top;
}

std::uint32_t clamp_add_subtract_full(std::uint32_t a, std::uint32_t b, std::uint32_t c)
{
    std::uint32_t out = 0;
    for (int shift = 0; shift < 32; shift += 8)
        out |= static_cast<std::uint32_t>(clip8(channel(a, shift) + channel(b, shift) - channel(c, shift))) << shift;
    return out;
}

std::uint32_t clamp_add_subtract_half(std::uint32_t a, std::uint32_t b)
{
    std::uint32_t out = 0;
    for (int shift = 0; shift < 32; shift += 8) {
        int const ca = channel(a, shift);
        out |= static_cast<std::uint32_t>(clip8(ca + (ca - channel(b, shift)) / 2)) << shift;
    }
    return out;
}

struct Transform {
    int type = 0;
    int bits = 0;
    int width = 0; // the image's width when the transform was read: what it applies to
    std::vector<std::uint32_t> data;
};

void inverse_predictor(Transform const& t, std::vector<std::uint32_t>& pixels, int width, int height)
{
    int const block_width = (width + (1 << t.bits) - 1) >> t.bits;
    for (int y = 0; y < height; ++y) {
        std::uint32_t* row = pixels.data() + static_cast<std::size_t>(y) * static_cast<std::size_t>(width);
        std::uint32_t const* up = y > 0 ? row - width : nullptr;
        for (int x = 0; x < width; ++x) {
            std::uint32_t predicted;
            if (y == 0) {
                predicted = x == 0 ? 0xff000000u : row[x - 1];
            } else if (x == 0) {
                predicted = up[0];
            } else {
                int const mode = static_cast<int>((t.data[static_cast<std::size_t>(y >> t.bits) * static_cast<std::size_t>(block_width)
                                                       + static_cast<std::size_t>(x >> t.bits)] >> 8) & 0xf);
                std::uint32_t const L = row[x - 1], T = up[x], TL = up[x - 1];
                std::uint32_t const TR = up[x + 1]; // the rightmost column's is the row's first pixel, which follows in memory
                switch (mode) {
                case 0: predicted = 0xff000000u; break;
                case 1: predicted = L; break;
                case 2: predicted = T; break;
                case 3: predicted = TR; break;
                case 4: predicted = TL; break;
                case 5: predicted = average2(average2(L, TR), T); break;
                case 6: predicted = average2(L, TL); break;
                case 7: predicted = average2(L, T); break;
                case 8: predicted = average2(TL, T); break;
                case 9: predicted = average2(T, TR); break;
                case 10: predicted = average2(average2(L, TL), average2(T, TR)); break;
                case 11: predicted = select_predictor(L, T, TL); break;
                case 12: predicted = clamp_add_subtract_full(L, T, TL); break;
                case 13: predicted = clamp_add_subtract_half(average2(L, T), TL); break;
                default: predicted = 0xff000000u; break;
                }
            }
            row[x] = add_pixels(row[x], predicted);
        }
    }
}

void inverse_cross_colour(Transform const& t, std::vector<std::uint32_t>& pixels, int width, int height)
{
    int const block_width = (width + (1 << t.bits) - 1) >> t.bits;
    auto const delta = [](int predictor, int colour) {
        return (static_cast<int>(static_cast<std::int8_t>(predictor)) * static_cast<int>(static_cast<std::int8_t>(colour))) >> 5;
    };
    for (int y = 0; y < height; ++y) {
        for (int x = 0; x < width; ++x) {
            std::uint32_t const code = t.data[static_cast<std::size_t>(y >> t.bits) * static_cast<std::size_t>(block_width)
                + static_cast<std::size_t>(x >> t.bits)];
            int const green_to_red = static_cast<int>(code & 0xff);
            int const green_to_blue = static_cast<int>((code >> 8) & 0xff);
            int const red_to_blue = static_cast<int>((code >> 16) & 0xff);
            std::uint32_t& argb = pixels[static_cast<std::size_t>(y) * static_cast<std::size_t>(width) + static_cast<std::size_t>(x)];
            int const green = static_cast<int>((argb >> 8) & 0xff);
            int red = static_cast<int>((argb >> 16) & 0xff);
            int blue = static_cast<int>(argb & 0xff);
            red = (red + delta(green_to_red, green)) & 0xff;
            blue = (blue + delta(green_to_blue, green)) & 0xff;
            blue = (blue + delta(red_to_blue, red)) & 0xff;
            argb = (argb & 0xff00ff00u) | (static_cast<std::uint32_t>(red) << 16) | static_cast<std::uint32_t>(blue);
        }
    }
}

// An image stream (§4, §5): the main image with its transforms, read in
// order and undone in reverse, or one of the images inside it.
std::optional<std::vector<std::uint32_t>> decode_image_stream(LsbReader& r, int width, int height, bool main_image,
    std::size_t max_pixels)
{
    if (width <= 0 || height <= 0 || static_cast<std::size_t>(width) * static_cast<std::size_t>(height) > max_pixels)
        return std::nullopt;
    std::vector<Transform> transforms;
    int coded_width = width;
    if (main_image) {
        bool seen[4] = {};
        while (r.read(1)) {
            Transform t;
            t.type = static_cast<int>(r.read(2));
            if (seen[t.type] || r.overrun())
                return std::nullopt;
            seen[t.type] = true;
            t.width = coded_width;
            if (t.type == 0 || t.type == 1) {
                t.bits = static_cast<int>(r.read(3)) + 2;
                int const bw = (coded_width + (1 << t.bits) - 1) >> t.bits;
                int const bh = (height + (1 << t.bits) - 1) >> t.bits;
                std::optional<std::vector<std::uint32_t>> data = decode_image_stream(r, bw, bh, false, max_pixels);
                if (!data)
                    return std::nullopt;
                t.data = std::move(*data);
            } else if (t.type == 3) {
                int const colours = static_cast<int>(r.read(8)) + 1;
                std::optional<std::vector<std::uint32_t>> palette = decode_image_stream(r, colours, 1, false, max_pixels);
                if (!palette)
                    return std::nullopt;
                for (std::size_t i = 1; i < palette->size(); ++i)
                    (*palette)[i] = add_pixels((*palette)[i], (*palette)[i - 1]);
                t.bits = colours > 16 ? 0 : colours > 4 ? 1 : colours > 2 ? 2 : 3;
                t.data = std::move(*palette);
                coded_width = (coded_width + (1 << t.bits) - 1) >> t.bits;
            }
            transforms.push_back(std::move(t));
        }
    }
    std::optional<std::vector<std::uint32_t>> pixels = decode_pixels(r, coded_width, height, main_image, max_pixels);
    if (!pixels)
        return std::nullopt;
    for (auto it = transforms.rbegin(); it != transforms.rend(); ++it) {
        Transform const& t = *it;
        switch (t.type) {
        case 0:
            inverse_predictor(t, *pixels, t.width, height);
            break;
        case 1:
            inverse_cross_colour(t, *pixels, t.width, height);
            break;
        case 2:
            for (std::uint32_t& argb : *pixels) {
                std::uint32_t const green = (argb >> 8) & 0xff;
                std::uint32_t const red_blue = ((argb & 0x00ff00ffu) + ((green << 16) | green)) & 0x00ff00ffu;
                argb = (argb & 0xff00ff00u) | red_blue;
            }
            break;
        case 3: {
            // Each packed pixel's green holds 1, 2, 4 or 8 indices.
            int const packed_width = (t.width + (1 << t.bits) - 1) >> t.bits;
            int const bits_per_index = 8 >> t.bits;
            std::uint32_t const mask = (1u << bits_per_index) - 1;
            std::vector<std::uint32_t> out(static_cast<std::size_t>(t.width) * static_cast<std::size_t>(height));
            for (int y = 0; y < height; ++y) {
                for (int x = 0; x < t.width; ++x) {
                    std::uint32_t const packed = (*pixels)[static_cast<std::size_t>(y) * static_cast<std::size_t>(packed_width)
                        + static_cast<std::size_t>(x >> t.bits)];
                    std::uint32_t const index = (((packed >> 8) & 0xff) >> ((x & ((1 << t.bits) - 1)) * bits_per_index)) & mask;
                    out[static_cast<std::size_t>(y) * static_cast<std::size_t>(t.width) + static_cast<std::size_t>(x)]
                        = index < t.data.size() ? t.data[index] : 0;
                }
            }
            *pixels = std::move(out);
            break;
        }
        default:
            break;
        }
    }
    return pixels;
}

std::optional<Bitmap> decode_vp8l(std::uint8_t const* data, std::size_t size, std::size_t max_pixels)
{
    if (size < 5 || data[0] != 0x2f)
        return std::nullopt;
    LsbReader r(data + 1, size - 1);
    int const width = static_cast<int>(r.read(14)) + 1;
    int const height = static_cast<int>(r.read(14)) + 1;
    r.read(1); // alpha_is_used: a hint, the pixels say
    if (r.read(3) != 0)
        return std::nullopt;
    std::optional<std::vector<std::uint32_t>> argb = decode_image_stream(r, width, height, true, max_pixels);
    if (!argb)
        return std::nullopt;
    std::vector<std::uint8_t> rgba(argb->size() * 4);
    for (std::size_t i = 0; i < argb->size(); ++i) {
        std::uint32_t const p = (*argb)[i];
        rgba[i * 4 + 0] = static_cast<std::uint8_t>(p >> 16);
        rgba[i * 4 + 1] = static_cast<std::uint8_t>(p >> 8);
        rgba[i * 4 + 2] = static_cast<std::uint8_t>(p);
        rgba[i * 4 + 3] = static_cast<std::uint8_t>(p >> 24);
    }
    return Bitmap(width, height, std::move(rgba));
}

// A lossy picture's alpha (RFC 9649 §3.4, the ALPH chunk): raw or a
// lossless image stream of the picture's size with the values in its green,
// then each row unfiltered against its neighbours.
bool apply_alpha(std::uint8_t const* data, std::size_t size, int width, int height, std::vector<std::uint8_t>& rgba,
    std::size_t max_pixels)
{
    if (size < 1)
        return false;
    int const compression = data[0] & 3;
    int const filtering = (data[0] >> 2) & 3;
    std::size_t const count = static_cast<std::size_t>(width) * static_cast<std::size_t>(height);
    std::vector<std::uint8_t> alpha(count);
    if (compression == 0) {
        if (size - 1 < count)
            return false;
        std::memcpy(alpha.data(), data + 1, count);
    } else if (compression == 1) {
        LsbReader r(data + 1, size - 1);
        std::optional<std::vector<std::uint32_t>> argb = decode_image_stream(r, width, height, true, max_pixels);
        if (!argb)
            return false;
        for (std::size_t i = 0; i < count; ++i)
            alpha[i] = static_cast<std::uint8_t>((*argb)[i] >> 8);
    } else {
        return false;
    }
    for (int y = 0; y < height; ++y) {
        std::uint8_t* row = alpha.data() + static_cast<std::size_t>(y) * static_cast<std::size_t>(width);
        std::uint8_t const* prev = y > 0 ? row - width : nullptr;
        if (filtering == 0)
            continue;
        if (filtering == 1 || !prev) {
            std::uint8_t pred = prev ? prev[0] : 0;
            for (int x = 0; x < width; ++x)
                pred = row[x] = static_cast<std::uint8_t>(pred + row[x]);
        } else if (filtering == 2) {
            for (int x = 0; x < width; ++x)
                row[x] = static_cast<std::uint8_t>(prev[x] + row[x]);
        } else {
            int top_left = prev[0], left = prev[0];
            for (int x = 0; x < width; ++x) {
                int const top = prev[x];
                left = static_cast<std::uint8_t>(row[x] + clip8(left + top - top_left));
                top_left = top;
                row[x] = static_cast<std::uint8_t>(left);
            }
        }
    }
    for (std::size_t i = 0; i < count; ++i)
        rgba[i * 4 + 3] = alpha[i];
    return true;
}

std::uint32_t le32(std::uint8_t const* p)
{
    return static_cast<std::uint32_t>(p[0]) | (static_cast<std::uint32_t>(p[1]) << 8) | (static_cast<std::uint32_t>(p[2]) << 16)
        | (static_cast<std::uint32_t>(p[3]) << 24);
}
std::uint32_t le24(std::uint8_t const* p)
{
    return static_cast<std::uint32_t>(p[0]) | (static_cast<std::uint32_t>(p[1]) << 8) | (static_cast<std::uint32_t>(p[2]) << 16);
}

struct Chunk {
    std::uint32_t fourcc;
    std::uint8_t const* data;
    std::size_t size;
};

constexpr std::uint32_t fourcc(char const (&s)[5])
{
    return static_cast<std::uint32_t>(static_cast<std::uint8_t>(s[0])) | (static_cast<std::uint32_t>(static_cast<std::uint8_t>(s[1])) << 8)
        | (static_cast<std::uint32_t>(static_cast<std::uint8_t>(s[2])) << 16) | (static_cast<std::uint32_t>(static_cast<std::uint8_t>(s[3])) << 24);
}

std::vector<Chunk> chunks_of(std::uint8_t const* data, std::size_t size)
{
    std::vector<Chunk> chunks;
    std::size_t pos = 0;
    while (pos + 8 <= size) {
        std::uint32_t const id = le32(data + pos);
        std::size_t const length = le32(data + pos + 4);
        pos += 8;
        if (length > size - pos)
            break;
        chunks.push_back({ id, data + pos, length });
        pos += length + (length & 1);
    }
    return chunks;
}

// One picture's chunks — an optional ALPH, then VP8 or VP8L — into RGBA.
std::optional<Bitmap> decode_frame(std::vector<Chunk> const& chunks, std::size_t max_pixels)
{
    Chunk const* alpha = nullptr;
    for (Chunk const& chunk : chunks) {
        if (chunk.fourcc == fourcc("ALPH")) {
            alpha = &chunk;
        } else if (chunk.fourcc == fourcc("VP8L")) {
            return decode_vp8l(chunk.data, chunk.size, max_pixels);
        } else if (chunk.fourcc == fourcc("VP8 ")) {
            std::optional<Planes> planes = decode_vp8(chunk.data, chunk.size, max_pixels);
            if (!planes)
                return std::nullopt;
            std::vector<std::uint8_t> rgba = planes_to_rgba(*planes);
            if (alpha && !apply_alpha(alpha->data, alpha->size, planes->width, planes->height, rgba, max_pixels))
                return std::nullopt;
            return Bitmap(planes->width, planes->height, std::move(rgba));
        }
    }
    return std::nullopt;
}

